#!/usr/bin/env bash
# Prints src/semantics/stdsource.byn for a std tree: every *.byn under <dir> (default lib/std) as one raw-string constant,
# in ordinal order of its path under <dir>, and stdShippedSources() listing them (spec 016 T2; ported from
# SelfhostStdSourceTests.Generate, spec 019 T26). scripts/ci/std-source.test.sh checks the file against it.
#   bash scripts/selfhost/gen-stdsource.sh [dir] > src/semantics/stdsource.byn
# Exit 1 when a file cannot be a raw string. bash 3.2, no dotnet.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
dir="${1:-$root/lib/std}"
cr=$(printf '\r'); nl=$'\n'
files=()
while IFS= read -r f; do files+=("$f"); done < <(cd "$dir" && LC_ALL=C find . -type f -name '*.byn' | sed 's|^\./||' | LC_ALL=C sort)
n=${#files[@]}
printf '// Generated by SelfhostStdSourceTests under BAYAN_UPDATE=1 from lib/std/; do not edit.\n\n'
printf '/// The C# `StdLibrary.Shipped` files (StdLibrary.cs:36): every `lib/std/**/*.byn`, its path under `std/`.\n'
printf 'List<StdSource> stdShippedSources() {\n'
if [ "$n" = 0 ]; then
  printf '    return List<StdSource>()\n'
else
  printf '    var sources = List<StdSource>()\n'
  i=0; while [ "$i" -lt "$n" ]; do
    printf '    sources.append(StdSource { path: "%s", text: stdSource%s })\n' "${files[$i]}" "$i"; i=$((i + 1))
  done
  printf '    return sources\n'
fi
printf '}\n'
i=0; while [ "$i" -lt "$n" ]; do
  f="${files[$i]}"
  text="$(sed "s/$cr\$//" "$dir/$f"; printf x)"; text="${text%x}"
  case "$text" in *'"""'*) echo "gen-stdsource: $f holds \"\"\"" >&2; exit 1 ;; esac
  case "$text" in ("$nl"*|*'"') echo "gen-stdsource: $f cannot be a raw string" >&2; exit 1 ;; esac
  case "$f" in *'"'*) echo "gen-stdsource: $f has a quote in its path" >&2; exit 1 ;; esac
  printf '\nconst stdSource%s: string = """%s"""\n' "$i" "$text"
  i=$((i + 1))
done
