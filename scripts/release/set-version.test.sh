#!/usr/bin/env bash
# set-version.sh on a fixture repo (scripts/docs/test-fixture.sh): every mirror and release doc header set (a body
# example left alone), check.sh passes after, a rerun changes nothing, refusals of a bad version and of a mirror
# with no version.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
t="$root/tmp/release-set-version-test"
rm -rf "$t" && mkdir -p "$t"
trap 'rm -rf "$t"' EXIT
. "$root/scripts/docs/test-fixture.sh"
docs_fixture "$t/repo"
r="$t/repo"; s="$r/scripts/release/set-version.sh"
fail() { echo "FAIL: $1" >&2; exit 1; }

# A release doc's body may show an example header; only the first ten lines are rewritten.
printf '\n\n\n\n\n\n\n\n```text\nVersion: 0.2.0 (matches `bayan --version`)\n```\n' >> "$r/docs/laws/README.md"
out="$(bash "$s" 1.3.0)"
for f in VERSION src/Bayan.Backend.C/Toolchain.cs selfhost/driver/main.byn tests/cases/out/dist.tree README.md \
  docs/bayan-spec.md docs/bayan-grammar.md docs/bayan-style.md docs/DIAGNOSTICS.md docs/STATUS.md docs/laws/README.md; do
  echo "$out" | grep -qx "changed $f" || fail "no 'changed $f' in: $out"
done
echo "$out" | grep -q "bootstrap/bayan.c is regenerated by scripts/selfhost/land.sh" || fail "no bootstrap note: $out"
[ "$(cat "$r/VERSION")" = 1.3.0 ] || fail "VERSION: $(cat "$r/VERSION")"
grep -qF 'CompilerVersion = "1.3.0";' "$r/src/Bayan.Backend.C/Toolchain.cs" || fail "Toolchain.cs"
grep -qx 'const version: string = "1.3.0"' "$r/selfhost/driver/main.byn" || fail "main.byn"
[ "$(grep -c '"compiler": "bayan 1.3.0"' "$r/tests/cases/out/dist.tree")" = 2 ] || fail "dist.tree: $(cat "$r/tests/cases/out/dist.tree")"
grep -qF 'dist/macos-arm64/1.3.0/bayan' "$r/README.md" || fail "README.md"
grep -qx 'Version: 1.3.0 (matches `bayan --version`)' "$r/docs/bayan-spec.md" || fail "SPEC header"
[ "$(grep -c '^Version: ' "$r/docs/laws/README.md")" = 2 ] && grep -qx 'Version: 0.2.0 (matches `bayan --version`)' "$r/docs/laws/README.md" \
  && grep -qx 'Version: 1.3.0 (matches `bayan --version`)' "$r/docs/laws/README.md" || fail "release doc header or body example: $(cat "$r/docs/laws/README.md")"
bash "$r/scripts/docs/check.sh" || fail "check.sh fails after set-version"
[ "$(bash "$s" 1.3.0 | grep -c '^changed ' || true)" = 0 ] || fail "a rerun changed files"

out="$(bash "$s" 1.3 2>&1)" && fail "bad version accepted"
echo "$out" | grep -q "'1.3' is not X.Y.Z" || fail "no bad-version message: $out"
sed -i.bak '1,10{/^Version: /d;}' "$r/docs/laws/README.md" && rm "$r/docs/laws/README.md.bak"   # only the body example is left
out="$(bash "$s" 1.4.0 2>&1)" && fail "release doc with a body Version: line only accepted"
echo "$out" | grep -q "docs/laws/README.md has no Version: line in its first ten lines" || fail "no header-missing message: $out"
[ "$(cat "$r/VERSION")" = 1.3.0 ] || fail "a refused header left VERSION at $(cat "$r/VERSION")"
{ printf 'Version: 1.3.0 (matches `bayan --version`)\n'; cat "$r/docs/laws/README.md"; } > "$t/h" && mv "$t/h" "$r/docs/laws/README.md"
printf 'no version here\n' > "$r/selfhost/driver/main.byn"
out="$(bash "$s" 1.4.0 2>&1)" && fail "mirror without a version accepted"
echo "$out" | grep -q "selfhost/driver/main.byn has no version to set" || fail "no missing-mirror message: $out"
echo PASS
