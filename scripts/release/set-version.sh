#!/usr/bin/env bash
# Sets the version everywhere it is written: VERSION, its code and test mirrors (version.sh `bayan_mirrors`) and the
# `Version:` line of each header doc (`bayan_header_docs`). Prints each file it changed; edits files only.
#   set-version.sh <version>      e.g. 0.3.0-dev or 0.3.0
# bootstrap/bayan.c is regenerated from selfhost/ by scripts/selfhost/land.sh, not edited here.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
. "$root/scripts/release/version.sh"
die() { echo "set-version: $*" >&2; exit 1; }

v="${1:?usage: set-version.sh <version>}"
bayan_valid_version "$v" || die "'$v' is not X.Y.Z or X.Y.Z-suffix"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT

# edit <file> <grep -E pattern that must match> <sed -E program>
edit() {
  local f="$root/$1"
  [ -f "$f" ] || die "$1 not found"
  grep -Eq "$2" "$f" || die "$1 has no version to set (pattern $2)"
  sed -E "$3" "$f" > "$tmp"
  if ! cmp -s "$tmp" "$f"; then cat "$tmp" > "$f"; echo "changed $1"; fi
}

printf '%s\n' "$v" > "$tmp"
if ! cmp -s "$tmp" "$root/VERSION"; then cat "$tmp" > "$root/VERSION"; echo "changed VERSION"; fi
while IFS=$'\t' read -r file pre suf; do
  edit "$file" "$pre[^\"/ ]+$suf" "s#$pre[^\"/ ]+$suf#\\1$v\\2#"
done < <(bayan_mirrors)
for doc in $bayan_header_docs; do
  edit "$doc" '^Version: [^ ]+ \(matches' "s/^Version: [^ ]+ \\(matches/Version: $v (matches/"
done
echo "bootstrap/bayan.c is regenerated by scripts/selfhost/land.sh, not edited here"
