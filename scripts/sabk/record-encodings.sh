#!/usr/bin/env bash
# Records the reference assembler's encodings of the sabk phase-1 subset (spec 024 R3). Expected bytes come only from here.
#   bash scripts/sabk/record-encodings.sh [input.s [output.tsv]]   (macOS only: needs zig and otool)
# Defaults: src/sabk/testdata/encodings.s -> src/sabk/testdata/encodings.tsv. Every instruction in the .s is preceded by a
# '// form: <id>' line; labels and directives carry no bytes. Fails if the assembler rejects the file or the instruction
# count differs from the word count.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="${1:-$root/src/sabk/testdata/encodings.s}"
out="${2:-$root/src/sabk/testdata/encodings.tsv}"
zig=zig; command -v zig >/dev/null 2>&1 || zig="$HOME/.local/bin/zig"
t="$root/tmp/sabk-record-$$"
mkdir -p "$t"
trap 'rm -rf "$t"' EXIT
"$zig" cc -c -target aarch64-macos "$src" -o "$t/e.o"
# otool -t prints "<addr> <word> <word> ..." with each 4-byte word as the little-endian u32 value.
otool -t "$t/e.o" | awk 'NF >= 2 && $1 ~ /^[0-9a-f]+$/ { for (i = 2; i <= NF; i++) print $i }' > "$t/words"
# form<TAB>assembler text, one per instruction line, in source order.
awk '
  /^[ \t]*\/\/ form:/ { sub(/^[ \t]*\/\/ form:[ \t]*/, ""); form = $0; next }
  /^[ \t]*(\/\/|$)/ || /^[ \t]*\./ || /^[A-Za-z_][A-Za-z0-9_]*:[ \t]*$/ { next }
  { sub(/^[ \t]+/, ""); sub(/[ \t]+$/, ""); if (form == "") { print "record-encodings: instruction without form: " $0 > "/dev/stderr"; exit 1 }
    printf "%s\t%s\n", form, $0; form = "" }
' "$src" > "$t/forms"
[ "$(wc -l < "$t/forms")" -eq "$(wc -l < "$t/words")" ] ||
  { echo "record-encodings: $(wc -l < "$t/forms") instructions but $(wc -l < "$t/words") words" >&2; exit 1; }
{
  echo "# form<TAB>assembler text<TAB>hex: the 4-byte word as the u32 value (little-endian read of the bytes), 8 lowercase hex digits. Generated by scripts/sabk/record-encodings.sh; do not edit."
  paste "$t/forms" "$t/words"
} > "$t/out.tsv"
mkdir -p "$(dirname "$out")"
cp "$t/out.tsv" "$out"
