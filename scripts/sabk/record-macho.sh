#!/usr/bin/env bash
# Records what the reference toolchain makes of the sabk phase-1 Mach-O module (spec 024 R5): the header, load commands, sections,
# relocations and symbols of a `clang -c` object, as tab-separated lines the writer test reads back. Expected values come only from here.
#   bash scripts/sabk/record-macho.sh [input.s [output.txt]]   (macOS only: needs clang, otool and nm)
# Defaults: src/sabk/testdata/macho.s -> src/sabk/testdata/macho-expected.txt. Numbers are decimal. Not recorded, because the
# writer legitimately differs: string table contents and offsets (n_strx, strsize), whose order and padding are the assembler's.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="${1:-$root/src/sabk/testdata/macho.s}"
out="${2:-$root/src/sabk/testdata/macho-expected.txt}"
t="$root/tmp/sabk-record-macho-$$"
mkdir -p "$t"
trap 'rm -rf "$t"' EXIT
clang -c -target arm64-apple-macos15.0 "$src" -o "$t/m.o"
# Symbol names in symbol-table order (nm -p keeps it); -x prints value, n_type, n_sect, n_desc, n_strx, name in hex.
nm -px "$t/m.o" | awk 'NF >= 6' > "$t/syms"
hex='function num(s,  r, i) { if (s !~ /^0x/) return s + 0; s = substr(s, 3); r = 0
  for (i = 1; i <= length(s); i++) r = r * 16 + index("0123456789abcdef", substr(s, i, 1)) - 1; return r }'
{
  echo "# kind<TAB>fields, from clang -c, otool -h/-l/-r and nm -px; numbers are decimal. Generated by scripts/sabk/record-macho.sh; do not edit."
  otool -h "$t/m.o" | awk "$hex"'
    NF == 8 && $1 ~ /^0x/ { printf "header\t%d\t%d\t%d\t%d\t%d\t%d\n", num($2), num($3), num($5), num($6), num($7), num($8) }'
  otool -l "$t/m.o" | awk "$hex"'
    /^Load command/ { insect = 0; next }
    /^Section/ { insect = 1; next }
    { v[$1] = $2 }
    $1 == "cmdsize" { printf "lc\t%s\t%d\n", v["cmd"], num($2) }
    $1 == "flags" && !insect { printf "segment\t%d\t%d\t%d\t%d\t%d\t%d\t%d\t%d\n", num(v["vmaddr"]), num(v["vmsize"]), v["fileoff"], v["filesize"], num(v["maxprot"]), num(v["initprot"]), v["nsects"], num($2) }
    $1 == "reserved2" { e = v["align"]; sub(/^2\^/, "", e); sub(/ .*/, "", e)
      printf "section\t%s\t%s\t%d\t%d\t%d\t%d\t%d\t%d\t%d\n", v["sectname"], v["segname"], num(v["addr"]), num(v["size"]), v["offset"], e, v["reloff"], v["nreloc"], num(v["flags"]) }
    $1 == "ntools" { printf "build\t%s\t%s\t%s\t%s\n", v["platform"], v["minos"], v["sdk"], v["ntools"] }
    $1 == "strsize" { printf "symtab\t%d\t%d\t%d\n", v["symoff"], v["nsyms"], v["stroff"] }
    $1 == "nlocrel" { printf "dysymtab"; split("ilocalsym nlocalsym iextdefsym nextdefsym iundefsym nundefsym tocoff ntoc modtaboff nmodtab extrefsymoff nextrefsyms indirectsymoff nindirectsyms extreloff nextrel locreloff nlocrel", k, " ")
      for (i = 1; i <= 18; i++) printf "\t%d", v[k[i]]; printf "\n" }'
  # Relocations: the symbol is named by its index in the symbol table.
  otool -r "$t/m.o" | awk "$hex"'
    BEGIN { while ((getline l < "'"$t"'/syms") > 0) { split(l, f, " "); names[n++] = f[6] } }
    /^Relocation information/ { sect = $3; gsub(/[()]/, "", sect); next }
    $1 ~ /^[0-9a-f]+$/ && NF == 7 { printf "reloc\t%s\t%d\t%d\t%d\t%d\t%d\t%d\t%s\n", sect, num("0x" $1), $2, $3, $4, $5, $6, names[$7] }'
  awk "$hex"'{ printf "sym\t%s\t%d\t%d\t%d\t%d\n", $6, num("0x" $2), num("0x" $3), num("0x" $4), num("0x" $1) }' "$t/syms"
} > "$t/out.txt"
mkdir -p "$(dirname "$out")"
cp "$t/out.txt" "$out"
