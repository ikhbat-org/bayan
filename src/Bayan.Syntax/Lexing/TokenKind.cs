    BarEquals,
    CaretEquals,
    LessLessEquals,

    // Keywords (spec §2.4). Order matters only for KeywordFirst/KeywordLast.
    StructKeyword,
    UniqueKeyword,
    UnionKeyword,
    EnumKeyword,
