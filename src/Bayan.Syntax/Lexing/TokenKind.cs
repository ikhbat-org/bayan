{
    EndOfFile,

    // Names and literals
    Identifier,
    IntegerLiteral,
    FloatLiteral,
    /// <summary>A suffix glued to a numeric literal: <c>5s</c>, <c>1u</c>, <c>1.5dec</c>.</summary>
    NumericSuffix,
    CharLiteral,
    StringLiteral,
    RawStringLiteral,
    CStringLiteral,
    U16StringLiteral,

    // Interpolated strings: $"a{x}b" lexes as Start Text HoleStart … HoleEnd Text End.
    InterpolatedStringStart,
    InterpolatedStringText,
    InterpolationStart,
    InterpolationEnd,
    InterpolatedStringEnd,

    // Punctuation
    OpenParen,
    CloseParen,
    OpenBracket,
    CloseBracket,
    OpenBrace,
    CloseBrace,
    Semicolon,
    Comma,
    Dot,
    DotDot,
    DotDotEquals,
    Colon,
    Question,
    QuestionQuestion,
    QuestionQuestionEquals,
    QuestionDot,
    FatArrow,
    Arrow,
    At,
    Hash,

    // Operators. `>>` and `>>=` are not tokens: the parser joins adjacent `>` tokens so that
    // `List<List<i64>>` closes two type argument lists.
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    PlusPercent,
    MinusPercent,
    StarPercent,
    PlusBar,
    MinusBar,
    StarBar,
