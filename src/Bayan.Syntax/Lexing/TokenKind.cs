    // Declaration-only, no meaning yet; contextual like the other declaration keywords.
    LawKeyword,
    // Effect aliases (§14), contextual.
    EffectKeyword,
    // Accepted for C# compatibility.
    ForeachKeyword,
    NewKeyword,
    // Lexed so the parser can explain that it does not exist.
    GotoKeyword,
    // Reserved: no meaning yet, may not be used as identifiers.
    ActorKeyword,
    MacroKeyword,
    SelectKeyword,
}

public static class TokenKindFacts
{
    public const TokenKind KeywordFirst = TokenKind.StructKeyword;
    public const TokenKind KeywordLast = TokenKind.SelectKeyword;

    public static bool IsKeyword(this TokenKind kind) => kind is >= KeywordFirst and <= KeywordLast;

    public static bool IsReservedKeyword(this TokenKind kind) => kind is >= TokenKind.ActorKeyword and <= KeywordLast;

    /// <summary>Declaration-only keywords that are names wherever the grammar does not need them as keywords.</summary>
    public static bool IsContextualKeyword(this TokenKind kind) => kind is
        TokenKind.ErrorKeyword or TokenKind.FlagsKeyword or TokenKind.UnitKeyword or TokenKind.DistinctKeyword or
        TokenKind.OpenKeyword or TokenKind.ExtensibleKeyword or TokenKind.SetKeyword or TokenKind.TypeKeyword or
        TokenKind.LawKeyword or TokenKind.DerivationKeyword or TokenKind.AttributeKeyword or TokenKind.EmbedKeyword or
        TokenKind.EffectKeyword;

    public static bool IsStringLiteral(this TokenKind kind) =>
        kind is TokenKind.StringLiteral or TokenKind.RawStringLiteral or TokenKind.CStringLiteral or TokenKind.U16StringLiteral;

    /// <summary>Source text of fixed tokens, for messages ("expected `;`").</summary>
    public static string Text(this TokenKind kind) => kind switch
    {
        TokenKind.EndOfFile => "end of file",
        TokenKind.Identifier => "identifier",
        TokenKind.IntegerLiteral => "integer literal",
        TokenKind.FloatLiteral => "float literal",
        TokenKind.NumericSuffix => "numeric suffix",
        TokenKind.CharLiteral => "char literal",
        TokenKind.StringLiteral or TokenKind.RawStringLiteral or TokenKind.CStringLiteral
            or TokenKind.U16StringLiteral => "string literal",
        TokenKind.InterpolatedStringStart => "$\"",
        TokenKind.InterpolatedStringText => "interpolated text",
        TokenKind.InterpolationStart => "{",
        TokenKind.InterpolationEnd => "}",
        TokenKind.InterpolatedStringEnd => "\"",
        TokenKind.OpenParen => "(",
        TokenKind.CloseParen => ")",
        TokenKind.OpenBracket => "[",
        TokenKind.CloseBracket => "]",
        TokenKind.OpenBrace => "{",
        TokenKind.CloseBrace => "}",
        TokenKind.Semicolon => ";",
        TokenKind.Comma => ",",
        TokenKind.Dot => ".",
        TokenKind.DotDot => "..",
        TokenKind.DotDotEquals => "..=",
        TokenKind.Colon => ":",
        TokenKind.Question => "?",
        TokenKind.QuestionQuestion => "??",
        TokenKind.QuestionQuestionEquals => "??=",
        TokenKind.QuestionDot => "?.",
        TokenKind.FatArrow => "=>",
        TokenKind.Arrow => "->",
        TokenKind.At => "@",
        TokenKind.Hash => "#",
        TokenKind.Plus => "+",
        TokenKind.Minus => "-",
        TokenKind.Star => "*",
        TokenKind.Slash => "/",
        TokenKind.Percent => "%",
        TokenKind.PlusPercent => "+%",
        TokenKind.MinusPercent => "-%",
        TokenKind.StarPercent => "*%",
        TokenKind.PlusBar => "+|",
        TokenKind.MinusBar => "-|",
        TokenKind.StarBar => "*|",
        TokenKind.PlusPlus => "++",
        TokenKind.MinusMinus => "--",
        TokenKind.Amp => "&",
        TokenKind.AmpAmp => "&&",
        TokenKind.Bar => "|",
        TokenKind.BarBar => "||",
        TokenKind.Caret => "^",
        TokenKind.Tilde => "~",
        TokenKind.Bang => "!",
        TokenKind.Equals => "=",
        TokenKind.EqualsEquals => "==",
        TokenKind.BangEquals => "!=",
        TokenKind.Less => "<",
        TokenKind.LessEquals => "<=",
        TokenKind.Greater => ">",
        TokenKind.GreaterEquals => ">=",
        TokenKind.LessLess => "<<",
        TokenKind.PlusEquals => "+=",
        TokenKind.MinusEquals => "-=",
        TokenKind.StarEquals => "*=",
        TokenKind.SlashEquals => "/=",
        TokenKind.PercentEquals => "%=",
        TokenKind.AmpEquals => "&=",
        TokenKind.BarEquals => "|=",
        TokenKind.CaretEquals => "^=",
        TokenKind.LessLessEquals => "<<=",
        _ when kind.IsKeyword() => Keywords.TextOf(kind),
        _ => kind.ToString(),
    };
}
