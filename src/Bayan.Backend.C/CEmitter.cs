using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Bayan.Lowering;
using Bayan.Semantics.Binding;
using Bayan.Semantics.Symbols;
using Bayan.Syntax.Ast;
using ArrayType = Bayan.Semantics.Symbols.ArrayType;
using OptionalType = Bayan.Semantics.Symbols.OptionalType;
using TupleType = Bayan.Semantics.Symbols.TupleType;

namespace Bayan.Backend.C;

/// <summary>Writes a <see cref="LoweredProgram"/> as one C11 translation unit that includes <c>bayan-rt.h</c>.</summary>
public sealed class CEmitter
{
    private readonly LoweredProgram _program;
    private readonly string _packageRoot;

    // Named C types (structs for optionals, spans, lists, arrays, tuples and user structs), by C name.
    private readonly Dictionary<string, TypeSymbol> _types = new(StringComparer.Ordinal);
    private readonly List<string> _typeOrder = new();

    // Generated helper functions: prototype and definition, by name.
    private readonly Dictionary<string, (string Proto, string Body)> _helpers = new(StringComparer.Ordinal);
    private readonly List<string> _helperOrder = new();

    // Static tables (enum names and values, `const` arrays), emitted after the types they use.
    private readonly Dictionary<string, string> _statics = new(StringComparer.Ordinal);
    private readonly List<string> _staticOrder = new();

    private readonly Dictionary<string, string> _files = new(StringComparer.Ordinal);
    private bool _hashes;

    // Symbol literal texts, numbered as first seen; `Run` sorts them into `byn_symtab` and puts each one's index there.
    private readonly List<string> _symbolTexts = new();
    private readonly Dictionary<string, int> _symbolIds = new(StringComparer.Ordinal);
    private bool _symbols;
    private const char SymbolMark = '\u0001';
    private readonly Dictionary<FunctionSymbol, int> _testIndex = new();

    private static readonly HashSet<string> CKeywords = new(StringComparer.Ordinal)
    {
        "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum", "extern",
        "float", "for", "goto", "if", "inline", "int", "long", "register", "restrict", "return", "short", "signed",
        "sizeof", "static", "struct", "switch", "typedef", "union", "unsigned", "void", "volatile", "while",
        "bool", "true", "false", "main", "errno", "stdin", "stdout", "stderr", "NULL", "asm", "typeof",
    };

    private CEmitter(LoweredProgram program, bool ownershipChecks)
    {
        _program = program;
        OwnershipChecks = ownershipChecks;
        _packageRoot = program.Compilation.PackageRoot;
        for (var i = 0; i < program.Tests.Count; i++) _testIndex[program.Tests[i].Function.Symbol] = i;
    }

    /// <summary>Debug builds only: emit the runtime ownership checker.</summary>
    internal bool OwnershipChecks { get; }

    public static string Emit(LoweredProgram program, bool ownershipChecks = false) => new CEmitter(program, ownershipChecks).Run();

    private string Run()
    {
        var bodies = new StringBuilder();
        var protos = new StringBuilder();
        var functions = _program.Functions.Concat(_program.Tests.Select(t => t.Function)).ToList();
        foreach (var f in functions)
        {
            var emitter = new FunctionEmitter(this, f);
            protos.Append(emitter.Signature()).Append(";\n");
            bodies.Append(emitter.Emit()).Append('\n');
        }
        var main = EmitMain();

        var errors = new StringBuilder();
        var variants = _program.Compilation.ErrorVariants;
        errors.Append("static const byn_str byn_errors[] = {\n");
        if (variants.Count == 0) errors.Append("    BYN_STR(\"\", 0),\n");
        foreach (var v in variants) errors.Append("    ").Append(StringLiteral(v.Summary)).Append(",\n");
        errors.Append("};\n\n");
        errors.Append("static __attribute__((unused)) void byn_w_error(byn_writer* w, uint32_t code) {\n");
        errors.Append($"    if (code == 0 || code > {variants.Count}) byn_w_str(w, BYN_STR(\"no error\", 8));\n");
        errors.Append("    else byn_w_str(w, byn_errors[code - 1]);\n}\n\n");
        errors.Append("static const uint8_t byn_exit_codes[] = {");
        errors.Append(variants.Count == 0 ? "1" : string.Join(", ", variants.Select(v => v.ExitCode)));
        errors.Append("};\n\n");

        var statics = new StringBuilder();
        foreach (var name in _staticOrder) statics.Append(_statics[name]);
        var symbolIndex = SymbolTable(statics);
        var types = EmitTypes();
        var enums = new StringBuilder();
        foreach (var e in _program.Compilation.Modules.SelectMany(m => m.Enums))
            enums.Append($"typedef int32_t {CType(e)};\n");
        if (enums.Length > 0) enums.Append('\n');

        var sb = new StringBuilder();
        sb.Append("/* Generated by the Bayan compiler. Do not edit. */\n");
        // The checker's runtime declarations, also when this file is compiled by hand without -DBYN_DEBUG.
        if (OwnershipChecks) sb.Append("#ifndef BYN_DEBUG\n#define BYN_DEBUG\n#endif\n");
        sb.Append("#include \"bayan-rt.h\"\n#include <math.h>\n#include <stdlib.h>\n\n");
        foreach (var (path, name) in _files)
            sb.Append($"static const char {name}[] = {CString(path)};\n");
        sb.Append('\n').Append(enums).Append(types).Append(statics).Append(errors);
        if (_program.Mutants) sb.Append(MutantSelector);
        if (_program.Coverage is { } coverage) sb.Append(CoverageCounters(coverage.Count));
        sb.Append(protos).Append('\n');
        foreach (var h in _helperOrder) sb.Append(_helpers[h].Proto).Append(";\n");
        sb.Append('\n');
        foreach (var v in _vtableOrder) sb.Append(_vtables[v]);
        if (_vtableOrder.Count > 0) sb.Append('\n');
        foreach (var h in _helperOrder) sb.Append(_helpers[h].Body).Append('\n');
        sb.Append(bodies).Append(main);
        var text = sb.ToString();
        // A literal's index is known once every literal is seen; the marks cannot clash, as `Escape` writes control bytes as octal.
        if (_symbols)
            text = Regex.Replace(text, $"{SymbolMark}(\\d+){SymbolMark}", m => symbolIndex[int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture)].ToString(CultureInfo.InvariantCulture));
        return ResolveResets(text);
    }

    /// <summary>Appends <c>byn_symtab</c>, the distinct literal texts sorted by UTF-8 bytes with <c>""</c> first (R2), and returns each literal's index by first-seen number.</summary>
    private int[] SymbolTable(StringBuilder sb)
    {
        if (!_symbols) return [];
        var sorted = _symbolTexts.Append("").Distinct(StringComparer.Ordinal)
            .Select(t => (Text: t, Bytes: Encoding.UTF8.GetBytes(t)))
            .OrderBy(t => t.Bytes, Comparer<byte[]>.Create((a, b) => a.AsSpan().SequenceCompareTo(b)))
            .Select(t => t.Text).ToList();
        sb.Append("static const byn_str byn_symtab[] = {\n");
        foreach (var t in sorted) sb.Append("    ").Append(StringLiteral(t)).Append(",\n");
        sb.Append("};\n\n");
        return _symbolTexts.Select(t => sorted.IndexOf(t)).ToArray();
    }

    /// <summary>A symbol literal; its ID is filled in by <see cref="Run"/>.</summary>
    internal string SymbolLiteral(string text)
    {
        _symbols = true;
        if (!_symbolIds.TryGetValue(text, out var k))
        {
            k = _symbolTexts.Count;
            _symbolIds[text] = k;
            _symbolTexts.Add(text);
        }
        return $"((byn_sym){{{SymbolMark}{k}{SymbolMark}}})";
    }

    /// <summary><c>s.text</c>: the interned text, which lives until the program exits.</summary>
    internal string SymbolText(string s)
    {
        _symbols = true;
        return $"byn_sym_text({s})";
    }

    /// <summary><c>Symbol.intern(text)</c>.</summary>
    internal string SymbolIntern(string text)
    {
        _symbols = true;
        return $"byn_sym_intern({text})";
    }

    /// <summary>The C file the emitted code is compiled as; generated code after a function's <c>#line</c>s maps back to it.</summary>
    internal const string GeneratedFile = "main.c";

    /// <summary>Written after a function body that maps lines to Bayan source; <see cref="ResolveResets"/> numbers it.</summary>
    internal const string ResetLine = "#line generated";

    /// <summary>Turns each <see cref="ResetLine"/> into <c>#line N "main.c"</c> naming the line after it, so debuggers step over generated code.</summary>
    private static string ResolveResets(string text)
    {
        if (!text.Contains(ResetLine, StringComparison.Ordinal)) return text;
        var lines = text.Split('\n');
        for (var i = 0; i < lines.Length; i++)
            if (lines[i] == ResetLine) lines[i] = $"#line {i + 2} {CString(GeneratedFile)}";
        return string.Join('\n', lines);
    }

    /// <summary>
    /// A <c>--mutate</c> build's selector: <c>BAYAN_MUTANT</c> read once at startup, the mutant that runs; unset, empty or
    /// not a decimal integer is 0, no mutant (spec 013 R2). With <c>BAYAN_SITE_REACH</c> set, every site whose switch the
    /// run evaluates is written, one id per line, to that path at exit (R8: the mutant-0 run records what each test reaches).
    /// </summary>
    private const string MutantSelector = """
        #include <stdio.h>

        static int64_t byn_mutant;
        static const char* byn_reach_path;
        static uint8_t* byn_reach_bits;
        static int64_t byn_reach_cap;

        static void byn_reach_write(void) {
            FILE* f = fopen(byn_reach_path, "w");
            if (f == NULL) return;
            for (int64_t i = 0; i < byn_reach_cap; i++)
                if (byn_reach_bits[i]) fprintf(f, "%lld\n", (long long)i);
            fclose(f);
        }

        static bool byn_mutant_is(int64_t id) {
            if (byn_reach_path != NULL && id >= 0 && id < INT32_MAX) {
                if (id >= byn_reach_cap) {
                    int64_t cap = id + 64;
                    uint8_t* bits = (uint8_t*)realloc(byn_reach_bits, (size_t)cap);
                    if (bits == NULL) abort();
                    memset(bits + byn_reach_cap, 0, (size_t)(cap - byn_reach_cap));
                    byn_reach_bits = bits;
                    byn_reach_cap = cap;
                }
                byn_reach_bits[id] = 1;
            }
            return byn_mutant == id;
        }

        static void byn_mutant_read(void) {
            const char* r = getenv("BAYAN_SITE_REACH");
            if (r != NULL && *r != 0) {
                byn_reach_path = r;
                atexit(byn_reach_write);
            }
            const char* s = getenv("BAYAN_MUTANT");
            int64_t n = 0;
            if (s == NULL || *s == 0) return;
            for (; *s != 0; s++) {
                if (*s < '0' || *s > '9' || n > (INT64_MAX - 9) / 10) return;
                n = n * 10 + (*s - '0');
            }
            byn_mutant = n;
        }


        """;

    /// <summary>
    /// A <c>--coverage</c> build's counters and their writer (spec 013 R9, R10). The counter file is the line
    /// <c>bayan-coverage 1</c>, then <c>&lt;counter id&gt; &lt;hits&gt;</c> per counter hit at least once. It is written
    /// once, at exit (<c>return</c> from <c>main</c> or <c>exit()</c>, through <c>atexit</c>) or on a panic (through the
    /// runtime's <c>byn_cov_flush</c>), and only when <c>BAYAN_COVERAGE</c> names a path prefix.
    /// </summary>
    private static string CoverageCounters(int count) => $$"""
        #include <stdio.h>
        #ifdef _WIN32
        #include <process.h>
        #define byn_cov_pid() ((unsigned long long)_getpid())
        #elif defined(__wasi__)
        #define byn_cov_pid() 0ULL
        #else
        #include <unistd.h>
        #define byn_cov_pid() ((unsigned long long)getpid())
        #endif

        static uint64_t byn_cov[{{Math.Max(count, 1).ToString(CultureInfo.InvariantCulture)}}];
        static char* byn_cov_path;

        static void byn_cov_write(void) {
            char* path = byn_cov_path;
            byn_cov_path = NULL;
            if (path == NULL) return;
            FILE* f = fopen(path, "w");
            free(path);
            if (f == NULL) return;
            fputs("bayan-coverage 1\n", f);
            for (size_t i = 0; i < sizeof byn_cov / sizeof byn_cov[0]; i++)
                if (byn_cov[i] != 0) fprintf(f, "%llu %llu\n", (unsigned long long)i, (unsigned long long)byn_cov[i]);
            fclose(f);
        }

        /* The file is `<BAYAN_COVERAGE>.<test index>` under `--test`, else `<BAYAN_COVERAGE>.<pid>`. */
        static void byn_cov_start(const char* test) {
            const char* prefix = getenv("BAYAN_COVERAGE");
            if (prefix == NULL || *prefix == 0) return;
            size_t n = strlen(prefix) + (test != NULL ? strlen(test) : 20) + 2;
            byn_cov_path = malloc(n);
            if (byn_cov_path == NULL) return;
            if (test != NULL) snprintf(byn_cov_path, n, "%s.%s", prefix, test);
            else snprintf(byn_cov_path, n, "%s.%llu", prefix, byn_cov_pid());
            byn_cov_flush = byn_cov_write;
            atexit(byn_cov_write);
        }


        """;

    private string CoverageStart() => _program.Tests.Count > 0
        ? "    byn_cov_start(argc == 3 && strcmp(argv[1], \"--test\") == 0 ? argv[2] : NULL);\n"
        : "    byn_cov_start(NULL);\n";

    private string EmitMain()
    {
        var sb = new StringBuilder();
        sb.Append($"int main(int argc, char** argv) {{\n    {ErrorCType} err = {{0}};\n");
        if (_program.Mutants) sb.Append("    byn_mutant_read();\n");
        if (_program.Coverage is not null) sb.Append(CoverageStart());
        // Map and symbol hashing is seeded per run; tests get a fixed seed so they are reproducible.
        if (_hashes || _symbols)
            sb.Append(_program.Tests.Count > 0
                ? "    byn_hash_seed_init(argc == 3 && strcmp(argv[1], \"--test\") == 0);\n"
                : "    byn_hash_seed_init(false);\n");
        // The literal table first and in order, so literal N is ID N and `Symbol.intern` of its text finds it.
        if (_symbols) sb.Append("    byn_sym_init(byn_symtab, (uint32_t)(sizeof byn_symtab / sizeof byn_symtab[0]));\n");
        if (_program.Tests.Count > 0)
        {
            sb.Append("    if (argc == 3 && strcmp(argv[1], \"--test\") == 0) {\n        switch (atoi(argv[2])) {\n");
            for (var i = 0; i < _program.Tests.Count; i++)
            {
                var fn = _program.Tests[i].Function.Symbol;
                sb.Append($"        case {i}: ").Append(fn.Fails ? "err = " : "").Append(FunctionName(fn)).Append("(); break;\n");
            }
            sb.Append("        default: return 2;\n        }\n");
            sb.Append("        if (err.code != 0) { byn_report_error(byn_errors[err.code - 1]); return 1; }\n");
            sb.Append("        byn_stdout_flush();\n        return 0;\n    }\n");
        }
        else
        {
            sb.Append("    (void)argv;\n");
        }
        var exit = "0";
        if (_program.Main is { } main)
        {
            // Arguments are checked for UTF-8 before `main` runs, whether or not it takes them.
            sb.Append("    byn_str* byn_argv = byn_args(&argc, argv);\n");
            var args = new List<string>();
            if (main.Parameters.Count == 1)
                args.Add($"({CType(main.Parameters[0].Type)}){{byn_argv, argc > 1 ? argc - 1 : 0}}");
            else
                sb.Append("    (void)byn_argv;\n");
            var returnsCode = main.ReturnType == PrimitiveType.I32;
            if (returnsCode)
            {
                sb.Append("    int32_t code = 0;\n");
                exit = "code";
            }
            if (main.Fails && returnsCode) args.Add("&code");
            var call = $"{FunctionName(main)}({string.Join(", ", args)})";
            sb.Append("    ").Append(main.Fails ? "err = " : returnsCode ? "code = " : "").Append(call).Append(";\n");
        }
        else
        {
            sb.Append("    (void)argc;\n");
        }
        sb.Append("    if (err.code != 0) { byn_report_error(byn_errors[err.code - 1]); return byn_exit_codes[err.code - 1]; }\n");
        sb.Append($"    byn_stdout_flush();\n    return {exit};\n}}\n");
        return sb.ToString();
    }

    // ── Names ────────────────────────────────────────────────────────────────────

    internal string FunctionName(FunctionSymbol f)
    {
        if (f.Kind == FunctionKind.Test) return "byn_test_" + _testIndex[f];
        var module = f.Module.CName;
        if (f.Kind == FunctionKind.Main) return $"byn_{module}__main";
        // `f$lambda2` in an instance of `f` is named after that instance, so each instantiation has its own.
        if (f.Kind == FunctionKind.Lambda) return FunctionName(f.Enclosing!) + "__lambda" + f.Name[(f.Name.LastIndexOf("$lambda", StringComparison.Ordinal) + 7)..];
        if (f.Owner is { } owner)
        {
            var member = f.Kind switch
            {
                FunctionKind.Constructor => "init" + owner.Constructors.IndexOf(f),
                FunctionKind.Getter => "get_" + f.Name,
                _ => f.Name + Overload(owner is StructSymbol s ? s.FindMethods(f.Name).ToList() : [], f),
            };
            return $"byn_{module}__{owner.Name}{TypeArgs(owner.TypeArguments)}__{member}";
        }
        return $"byn_{module}__{f.Name}{Overload(f.Module.Functions.GetValueOrDefault(f.Name) ?? [], f.Template ?? f)}{TypeArgs(f.TypeArguments)}";
    }

    /// <summary>The <c>__o1</c> that tells a second overload from the first (J65); empty for the first.</summary>
    private static string Overload(List<FunctionSymbol> overloads, FunctionSymbol f) => overloads.IndexOf(f) is > 0 and var i ? "__o" + i : "";

    /// <summary>The <c>__i64__str</c> that tells instantiations of one generic apart.</summary>
    private string TypeArgs(IReadOnlyList<TypeSymbol> args) => string.Concat(args.Select(a => "__" + Key(a)));

    internal static string FieldName(string name) => CKeywords.Contains(name) ? name + "_" : name;

    internal string FileName(FunctionSymbol f)
    {
        var relative = FilePath(f);
        if (!_files.TryGetValue(relative, out var name))
        {
            name = "byn_file_" + _files.Count;
            _files[relative] = name;
        }
        return name;
    }

    /// <summary>The path panics and <c>#line</c> name <paramref name="f"/>'s file by.</summary>
    internal string FilePath(FunctionSymbol f)
    {
        var path = f.File?.Source.Path ?? "";
        // Project files are already relative to the project root; a loose file is named from its directory.
        var relative = Path.IsPathRooted(path) ? Path.GetRelativePath(_packageRoot, path).Replace('\\', '/') : path.Replace('\\', '/');
        if (relative.StartsWith("..", StringComparison.Ordinal)) relative = Path.GetFileName(path);
        return relative;
    }

    // ── Types ────────────────────────────────────────────────────────────────────

    internal string CType(TypeSymbol t) => t switch
    {
        PrimitiveType p => p.Kind switch
        {
            PrimitiveKind.I8 => "int8_t",
            PrimitiveKind.I16 => "int16_t",
            PrimitiveKind.I32 => "int32_t",
            PrimitiveKind.I64 or PrimitiveKind.Isize => "int64_t",
            PrimitiveKind.U8 => "uint8_t",
            PrimitiveKind.U16 => "uint16_t",
            PrimitiveKind.U32 or PrimitiveKind.Char => "uint32_t",
            PrimitiveKind.U64 or PrimitiveKind.Usize => "uint64_t",
            PrimitiveKind.F32 => "float",
            PrimitiveKind.F64 => "double",
            PrimitiveKind.Bool => "bool",
            PrimitiveKind.String => "byn_str",
            _ => "void",
        },
        // One error type for the program: every set converts to every union of sets without changing its bits.
        ErrorSetSymbol or ErrorUnionType => Named(t, "byn_err"),
        EnumSymbol e => $"byn_{e.Module.CName}_{e.Name}",
        UnionSymbol u => Named(u, $"byn_{u.Module.CName}_{u.Name}{TypeArgs(u.TypeArguments)}"),
        BuiltinType { Kind: BuiltinKind.Arena } => "byn_arena*",
        BuiltinType { Kind: BuiltinKind.StrBuf } => "byn_writer",
        BuiltinType { Kind: BuiltinKind.IoStream or BuiltinKind.IoInput } => "int32_t",
        BuiltinType { Kind: BuiltinKind.ProcessResult } => "byn_process",
        BuiltinType { Kind: BuiltinKind.Panic } => "byn_panic_info",
        BuiltinType { Kind: BuiltinKind.FormatSpec } => "byn_format_spec",
        BuiltinType { Kind: BuiltinKind.Symbol } => "byn_sym",
        TextViewType => "byn_text_view",
        // A pointer needs only the forward typedef, so a type may hold an `Owned` of itself.
        OwnedType o => CType(o.Inner) + "*",
        UntrustedType u => CType(u.Inner),
        // A state type is stored as its struct, which carries the tag.
        StateType st => CType(st.Struct),
        // `dyn ref readonly I` shares the C type of `dyn ref I`.
        DynRefType d => Named(t, "byn_dyn_" + Key(d.Interface)),
        RangeType r => CType(r.Layout),
        _ => Named(t),
    };

    /// <summary>The C type of every error, and of what a failing function returns.</summary>
    internal string ErrorCType => CType(ErrorUnionType.Of([]));

    /// <summary>An identifier fragment naming a type, for generated type and helper names.</summary>
    internal string Key(TypeSymbol t) => t switch
    {
        PrimitiveType p => p.Kind == PrimitiveKind.String ? "str" : p.Name,
        ErrorSetSymbol or ErrorUnionType => "err",
        BuiltinType b => b.Kind switch { BuiltinKind.Arena => "arena", BuiltinKind.StrBuf => "strbuf", BuiltinKind.ProcessResult => "process", BuiltinKind.Panic => "panic", BuiltinKind.FormatSpec => "formatspec", BuiltinKind.Symbol => "sym", _ => "iostream" },
        StructSymbol s => s.Module.CName + "__" + s.Name + TypeArgs(s.TypeArguments),
        EnumSymbol e => e.Module.CName + "__" + e.Name,
        UnionSymbol u => u.Module.CName + "__" + u.Name + TypeArgs(u.TypeArguments),
        InterfaceSymbol i => i.Module.CName + "__" + i.Name + TypeArgs(i.TypeArguments),
        DynRefType d => "dyn_" + Key(d.Interface),
        OptionalType o => "opt_" + Key(o.Inner),
        ResultType r => "res_" + Key(r.Value),
        SpanType s => "span_" + Key(s.Element),
        TextViewType => "textview",
        ListType l => "list_" + Key(l.Element),
        OwnedType o => "own_" + Key(o.Inner),
        UntrustedType u => Key(u.Inner),
        StateType st => Key(st.Struct),
        MapType m => "map_" + Key(m.KeyType) + "_" + Key(m.ValueType),
        ArrayType a => $"arr{a.Length}_" + Key(a.Element),
        TupleType tt => $"tup{tt.Fields.Count}_" + string.Join("_", tt.Fields.Select(f => Key(f.Type))),
        RangeType r => Key(r.Layout),
        // The fails and uses markers come before the return key, so a nested function type cannot share a key with an outer one.
        FunctionType f => $"fn{f.Parameters.Count}" + (f.Fails.Count > 0 ? "f" : "") + (f.Uses.Count > 0 ? $"u{f.Uses.Count}" : "") + "_" + string.Concat(f.Parameters.Select(p => Key(p) + "_")) + string.Concat(f.Uses.Select(u => u + "_")) + Key(f.Return),
        _ => throw new InvalidOperationException($"no C type for {t.DisplayName}"),
    };

    private string Named(TypeSymbol t, string? name = null)
    {
        name ??= "bynt_" + Key(t);
        if (_types.TryAdd(name, t)) _typeOrder.Add(name);
        return name;
    }

    /// <summary>Forward typedefs for every named type, then the definitions with by-value members first.</summary>
    private string EmitTypes()
    {
        var defs = new StringBuilder();
        var done = new HashSet<string>(StringComparer.Ordinal);
        void Define(string name)
        {
            if (!done.Add(name)) return;
            var t = _types[name];
            var members = new List<(TypeSymbol Type, string Decl)>();
            var payloads = new List<TypeSymbol>();
            switch (t)
            {
                case StructSymbol s:
                    foreach (var f in s.Fields) members.Add((f.Type, $"{CType(f.Type)} {FieldName(f.Name)}"));
                    if (_program.Compilation.States.TryGetValue(s, out var states))
                    {
                        // After the fields, the state's tag and its payload, laid out like a union (spec §3.17).
                        members.Add((PrimitiveType.U8, "uint8_t tag"));
                        var held = states.Variants.Where(v => v.Fields.Count > 0).ToList();
                        if (held.Count > 0)
                            members.Add((PrimitiveType.U8, "union {\n" + string.Concat(held.Select(v =>
                                $"        struct {{ {string.Concat(v.Fields.Select(f => $"{CType(f.Type)} {FieldName(f.Name)}; "))}}} {FieldName(v.Name)};\n")) + "    } u"));
                        payloads.AddRange(held.SelectMany(v => v.Fields).Select(f => f.Type));
                    }
                    else if (s.Fields.Count == 0) members.Add((PrimitiveType.Bool, "char unused"));
                    break;
                case OptionalType o:
                    members.Add((PrimitiveType.Bool, "bool has"));
                    members.Add((o.Inner, $"{CType(o.Inner)} value"));
                    break;
                case ErrorSetSymbol or ErrorUnionType:
                {
                    // The code, then the largest payload: a case with fields has a struct named by its code (SPEC §3.12).
                    members.Add((PrimitiveType.U32, "uint32_t code"));
                    var cases = _program.Compilation.ErrorVariants.Where(v => v.Fields.Count > 0).ToList();
                    if (cases.Count > 0)
                        members.Add((PrimitiveType.U32, "union {\n" + string.Concat(cases.Select(v =>
                            $"        struct {{ {string.Concat(v.Fields.Select(f => $"{CType(f.Type)} {FieldName(f.Name)}; "))}}} e{v.Code};\n")) + "    } p"));
                    payloads.AddRange(cases.SelectMany(v => v.Fields).Select(f => f.Type));
                    break;
                }
                case ResultType r:
                    members.Add((r.Error, $"{CType(r.Error)} err"));
                    members.Add((r.Value, $"{CType(r.Value)} value"));
                    break;
                case SpanType sp:
                    members.Add((PrimitiveType.I64, $"{CType(sp.Element)}* ptr"));
                    members.Add((PrimitiveType.I64, "int64_t len"));
                    break;
                case ListType l:
                    members.Add((PrimitiveType.I64, $"{CType(l.Element)}* ptr"));
                    members.Add((PrimitiveType.I64, "int64_t len"));
                    members.Add((PrimitiveType.I64, "int64_t cap"));
                    members.Add((PrimitiveType.I64, "byn_alloc* alloc"));
                    break;
                case MapType m:
                    members.Add((PrimitiveType.I64, "byn_map_hdr h"));
                    members.Add((PrimitiveType.I64, $"{CType(m.KeyType)}* keys"));
                    members.Add((PrimitiveType.I64, $"{CType(m.ValueType)}* vals"));
                    break;
                case ArrayType a:
                    members.Add((a.Element, $"{CType(a.Element)} v[{a.Length}]"));
                    break;
                case TupleType tt:
                    for (var i = 0; i < tt.Fields.Count; i++) members.Add((tt.Fields[i].Type, $"{CType(tt.Fields[i].Type)} item{i + 1}"));
                    break;
                case DynRefType d:
                {
                    // Slot parameters may be incomplete types, so the table needs no other definition first.
                    var vt = "byn_vt_" + Key(d.Interface);
                    defs.Append($"struct {vt} {{\n");
                    foreach (var m in Slots(d.Interface))
                        defs.Append($"    {SlotSignature(m, $"(*{SlotName(m)})", out _)};\n");
                    defs.Append("};\n\n");
                    members.Add((PrimitiveType.I64, "void* data"));
                    members.Add((PrimitiveType.I64, $"const struct {vt}* vt"));
                    break;
                }
                case FunctionType f:
                    // The code and the environment it is called with; parameter and return types need only their typedefs.
                    members.Add((PrimitiveType.I64, FunctionSignature(f, "(*fn)", out _)));
                    members.Add((PrimitiveType.I64, "void* env"));
                    break;
                case UnionSymbol u:
                {
                    // Unit variants have no struct; a union of only unit variants has no `u`.
                    members.Add((PrimitiveType.I32, "int32_t tag"));
                    var variants = u.Variants.Where(v => v.Fields.Count > 0).ToList();
                    if (variants.Count > 0)
                        members.Add((PrimitiveType.I32, "union {\n" + string.Concat(variants.Select(v =>
                            $"        struct {{ {string.Concat(v.Fields.Select(f => $"{CType(f.Type)} {FieldName(f.Name)}; "))}}} {FieldName(v.Name)};\n")) + "    } u"));
                    payloads.AddRange(variants.SelectMany(v => v.Fields).Select(f => f.Type));
                    break;
                }
            }
            foreach (var type in members.Select(m => m.Type).Concat(payloads))
                if (type is not PrimitiveType && CType(type) is var dep && _types.ContainsKey(dep)) Define(dep);
            defs.Append($"struct {name} {{\n");
            foreach (var (_, decl) in members) defs.Append("    ").Append(decl).Append(";\n");
            defs.Append("};\n\n");
        }
        // Defining a type can name new ones (an element type), so iterate to a fixed point.
        for (var i = 0; i < _typeOrder.Count; i++) Define(_typeOrder[i]);
        var sb = new StringBuilder();
        foreach (var name in _typeOrder) sb.Append($"typedef struct {name} {name};\n");
        sb.Append('\n').Append(defs);
        return sb.ToString();
    }

    // ── Helpers ──────────────────────────────────────────────────────────────────

    /// <summary>Registers a generated helper once; <paramref name="body"/> may register others.</summary>
    internal string Helper(string name, string proto, Func<string> body)
    {
        if (_helpers.ContainsKey(name)) return name;
        _helpers[name] = (proto, "");
        _helperOrder.Add(name);
        _helpers[name] = (proto, proto + " " + body());
        return name;
    }

    // ── dyn ref ──────────────────────────────────────────────────────────────────

    /// <summary>The vtable slots of <paramref name="i"/>: one per method and getter, defaults included.</summary>
    private static IEnumerable<FunctionSymbol> Slots(InterfaceSymbol i) => i.Methods.Concat(i.Properties);

    internal static string SlotName(FunctionSymbol m) => m.Kind == FunctionKind.Getter ? "get_" + m.Name : FieldName(m.Name);

    /// <summary>A slot's C signature around <paramref name="declarator"/>, in <c>Signature</c>'s <c>fails</c> convention with
    /// <c>void* self</c> first; <paramref name="args"/> are the names of the parameters after <c>self</c>.</summary>
    private string SlotSignature(FunctionSymbol m, string declarator, out List<string> args)
    {
        var returnsValue = !m.ReturnType.IsVoid && !m.ReturnType.IsNever;
        var ps = new List<string> { "void* self" };
        args = new List<string>();
        for (var k = 0; k < m.Parameters.Count; k++)
        {
            args.Add("a" + k);
            ps.Add($"{CType(m.Parameters[k].Type)}{(m.Parameters[k].IsByRef ? "*" : "")} a{k}");
        }
        if (m.Fails && returnsValue)
        {
            args.Add("byn_out");
            ps.Add($"{CType(m.ReturnType)}* byn_out");
        }
        return $"{(m.Fails ? ErrorCType : CType(m.ReturnType))} {declarator}({string.Join(", ", ps)})";
    }

    /// <summary>A function type's C signature around <paramref name="declarator"/>, in <c>Signature</c>'s <c>fails</c> convention with
    /// <c>void* env</c> first; <paramref name="args"/> are the names of the parameters after <c>env</c>.</summary>
    internal string FunctionSignature(FunctionType f, string declarator, out List<string> args)
    {
        var fails = f.Fails.Count > 0;
        var ps = new List<string> { "void* env" };
        args = new List<string>();
        for (var k = 0; k < f.Parameters.Count; k++)
        {
            args.Add("a" + k);
            ps.Add($"{CType(f.Parameters[k])} a{k}");
        }
        if (fails && !f.Return.IsVoid && !f.Return.IsNever)
        {
            args.Add("byn_out");
            ps.Add($"{CType(f.Return)}* byn_out");
        }
        return $"{(fails ? ErrorCType : CType(f.Return))} {declarator}({string.Join(", ", ps)})";
    }

    /// <summary>A named function as a value of <paramref name="type"/>: a thunk that takes and ignores the environment.</summary>
    internal string FunctionThunk(FunctionSymbol fn, FunctionType type)
    {
        var name = "bynh_fnthunk_" + FunctionName(fn);
        var proto = "static " + FunctionSignature(type, name, out var args);
        var returns = type.Fails.Count > 0 || (!type.Return.IsVoid && !type.Return.IsNever);
        return Helper(name, proto, () => $"{{\n    (void)env;\n    {(returns ? "return " : "")}{FunctionName(fn)}({string.Join(", ", args)});\n}}\n");
    }

    // Vtables, one per (conformer, interface) converted to `dyn ref`, emitted after the helper prototypes they point at.
    private readonly Dictionary<string, string> _vtables = new(StringComparer.Ordinal);
    private readonly List<string> _vtableOrder = new();

    /// <summary>The vtable of <paramref name="s"/> as <paramref name="i"/>, with a thunk per slot casting <c>self</c> to the conformer.</summary>
    internal string Vtable(StructSymbol s, InterfaceSymbol i)
    {
        var name = $"bynh_vtab_{Key(s)}_{Key(i)}";
        if (_vtables.ContainsKey(name)) return name;
        var conformance = s.Conformances.First(c => c.Interface == i);
        var thunks = new List<string>();
        foreach (var m in Slots(i))
        {
            var thunk = $"bynh_vt_{Key(s)}_{Key(i)}_{SlotName(m)}";
            var proto = "static " + SlotSignature(m, thunk, out var args);
            var call = conformance.FieldWitnesses.TryGetValue(m, out var field)
                ? $"(({CType(s)}*)self)->{FieldName(field.Name)}"
                : $"{FunctionName(conformance.Witnesses[m])}({string.Join(", ", args.Prepend($"({CType(s)}*)self"))})";
            var returns = m.Fails || (!m.ReturnType.IsVoid && !m.ReturnType.IsNever);
            thunks.Add(Helper(thunk, proto, () => $"{{\n    {(returns ? "return " : "")}{call};\n}}\n"));
        }
        _vtables[name] = $"static const struct byn_vt_{Key(i)} {name} = {{ {string.Join(", ", thunks)} }};\n";
        _vtableOrder.Add(name);
        return name;
    }

    // ── Ownership checker (debug builds) ────────────────────────────────────────

    /// <summary>The storage a <paramref name="t"/> at lvalue <paramref name="at"/> owns by value: a List's elements, a Map's keys,
    /// a growable StrBuf's bytes, an Owned box, through struct fields and tuple items (not optionals, unions or arrays).</summary>
    private static void StorageParts(TypeSymbol t, string at, List<(string Storage, string Place, string Type)> parts)
    {
        switch (t)
        {
            case ListType:
                parts.Add(($"{at}.ptr", "&" + at, t.DisplayName));
                break;
            case MapType:
                parts.Add(($"{at}.keys", "&" + at, t.DisplayName));
                break;
            case BuiltinType { Kind: BuiltinKind.StrBuf }:
                parts.Add(($"({at}.mode == BYN_WRITE_GROW ? {at}.buf : NULL)", "&" + at, t.DisplayName));
                break;
            case OwnedType:
                parts.Add((at, "&" + at, t.DisplayName));
                break;
            case UntrustedType u:
                StorageParts(u.Inner, at, parts);
                break;
            case TupleType tt:
                for (var i = 0; i < tt.Fields.Count; i++) StorageParts(tt.Fields[i].Type, $"{at}.item{i + 1}", parts);
                break;
            case StructSymbol s:
                foreach (var f in s.Fields) StorageParts(f.Type, $"{at}.{FieldName(f.Name)}", parts);
                break;
            case StateType st:
                StorageParts(st.Struct, at, parts);
                break;
        }
    }

    internal static bool OwnsStorage(TypeSymbol t)
    {
        var parts = new List<(string, string, string)>();
        StorageParts(t, "v", parts);
        return parts.Count > 0;
    }

    private string OwnStatements(TypeSymbol t, string at, Func<(string Storage, string Place, string Type), string> line)
    {
        var parts = new List<(string Storage, string Place, string Type)>();
        StorageParts(t, at, parts);
        return string.Concat(parts.Select(p => "    " + line(p) + ";\n"));
    }

    /// <summary>Records <c>*p</c> as the owner of its storage.</summary>
    internal string OwnClaim(TypeSymbol t)
    {
        var ct = CType(t);
        var name = "bynh_chk_claim_" + Key(t);
        return Helper(name, $"static void {name}({ct}* p, const char* file, int line)", () =>
            "{\n" + OwnStatements(t, "(*p)", p => $"byn_own_claim({p.Storage}, {p.Place}, {CString(p.Type)}, file, line)") + "}\n");
    }

    /// <summary>Stores <c>v</c> into <c>*p</c>: storage <c>*p</c> owned is let go, the local's moved slot (if any) is cleared,
    /// and with <c>claim</c> <c>*p</c> owns the new storage.</summary>
    internal string OwnSet(TypeSymbol t)
    {
        var ct = CType(t);
        var name = "bynh_chk_set_" + Key(t);
        return Helper(name, $"static {ct} {name}({ct}* p, {ct} v, byn_own_slot* s, bool claim, const char* file, int line)", () =>
            "{\n" + OwnStatements(t, "(*p)", p => $"byn_own_drop({p.Storage}, {p.Place})") +
            $"    *p = v;\n    if (s) s->line = 0;\n    if (claim) {OwnClaim(t)}(p, file, line);\n    return v;\n}}\n");
    }

    /// <summary><c>move</c> of a local: its storage leaves it, and its moved slot (if given) records where.</summary>
    internal string OwnMove(TypeSymbol t)
    {
        var ct = CType(t);
        var name = "bynh_chk_move_" + Key(t);
        return Helper(name, $"static {ct}* {name}({ct}* p, byn_own_slot* s, const char* file, int line)", () =>
            "{\n" + $"    if (s) byn_own_read(s, {CString(t.DisplayName)}, file, line);\n" +
            OwnStatements(t, "(*p)", p => $"byn_own_release({p.Storage})") +
            "    if (s) {\n        s->file = file;\n        s->line = line;\n    }\n    return p;\n}\n");
    }

    /// <summary>A returned value's storage leaves the function.</summary>
    internal string OwnReturn(TypeSymbol t)
    {
        var ct = CType(t);
        var name = "bynh_chk_ret_" + Key(t);
        return Helper(name, $"static {ct} {name}({ct} v)", () =>
            "{\n" + OwnStatements(t, "v", p => $"byn_own_release({p.Storage})") + "    return v;\n}\n");
    }

    internal static string IntSuffix(TypeSymbol t) => ((PrimitiveType)t).Kind switch
    {
        PrimitiveKind.Isize => "i64",
        PrimitiveKind.Usize => "u64",
        var k => k.ToString().ToLowerInvariant(),
    };

    /// <summary><c>a == b</c> for any equatable type.</summary>
    internal string Equal(TypeSymbol t, string a, string b)
    {
        switch (t)
        {
            case PrimitiveType { IsString: true }:
                return $"byn_str_eq({a}, {b})";
            case PrimitiveType or EnumSymbol:
                return $"({a} == {b})";
            case BuiltinType { Kind: BuiltinKind.Symbol }:
                return $"(({a}).id == ({b}).id)";
            case ErrorSetSymbol or ErrorUnionType:
            {
                // By code, then the payload of a case that has one (Q45, Q28). One helper serves every set, as the
                // `Result`, optional and tuple helpers are keyed without theirs; a case whose payload has no equality is
                // left out, since `==` on its set does not bind (Q344).
                var cases = _program.Compilation.ErrorVariants
                    .Where(v => v.Fields.Count > 0 && v.Fields.All(f => Semantics.Compilation.IsEquatable(f.Type))).ToList();
                if (cases.Count == 0) return $"({a}.code == {b}.code)";
                var eq = Helper("bynh_eq_err", $"static bool bynh_eq_err({ErrorCType} a, {ErrorCType} b)", () =>
                {
                    var sb = new StringBuilder("{\n    if (a.code != b.code) return false;\n    switch (a.code) {\n");
                    foreach (var v in cases)
                    {
                        var fields = v.Fields.Select(f => Equal(f.Type, $"a.p.e{v.Code}.{FieldName(f.Name)}", $"b.p.e{v.Code}.{FieldName(f.Name)}"));
                        sb.Append($"    case {v.Code}: return {string.Join("\n        && ", fields)};\n");
                    }
                    return sb.Append("    }\n    return true;\n}\n").ToString();
                });
                return $"{eq}({a}, {b})";
            }
            case OwnedType o:
                return Equal(o.Inner, $"(*{a})", $"(*{b})");
            case UntrustedType u:
                return Equal(u.Inner, a, b);
            case StateType st:
                return Equal(st.Struct, a, b);
        }
        var ct = CType(t);
        var name = "bynh_eq_" + Key(t);
        Helper(name, $"static bool {name}({ct} a, {ct} b)", () =>
        {
            if (t is UnionSymbol u)
            {
                var sb = new StringBuilder("{\n    if (a.tag != b.tag) return false;\n    switch (a.tag) {\n");
                foreach (var v in u.Variants.Where(v => v.Fields.Count > 0))
                {
                    var fields = v.Fields.Select(f => Equal(f.Type, $"a.u.{FieldName(v.Name)}.{FieldName(f.Name)}", $"b.u.{FieldName(v.Name)}.{FieldName(f.Name)}"));
                    sb.Append($"    case {v.Tag}: return {string.Join("\n        && ", fields)};\n");
                }
                return sb.Append("    default: return true;\n    }\n}\n").ToString();
            }
            if (t is StructSymbol ss && _program.Compilation.States.TryGetValue(ss, out var states))
            {
                // The fields, then the tag, then the payload of the state both are in.
                var sb = new StringBuilder("{\n");
                foreach (var f in ss.Fields)
                    sb.Append($"    if (!{Equal(f.Type, "a." + FieldName(f.Name), "b." + FieldName(f.Name))}) return false;\n");
                sb.Append("    if (a.tag != b.tag) return false;\n    switch (a.tag) {\n");
                foreach (var v in states.Variants.Where(v => v.Fields.Count > 0))
                {
                    var fields = v.Fields.Select(f => Equal(f.Type, $"a.u.{FieldName(v.Name)}.{FieldName(f.Name)}", $"b.u.{FieldName(v.Name)}.{FieldName(f.Name)}"));
                    sb.Append($"    case {v.Tag}: return {string.Join("\n        && ", fields)};\n");
                }
                return sb.Append("    default: return true;\n    }\n}\n").ToString();
            }
            if (t is ArrayType arr)
                return $"{{\n    for (int64_t i = 0; i < {arr.Length}; i++)\n        if (!{Equal(arr.Element, "a.v[i]", "b.v[i]")}) return false;\n    return true;\n}}\n";
            List<string> tests = t switch
            {
                OptionalType o => [$"a.has == b.has && (!a.has || {Equal(o.Inner, "a.value", "b.value")})"],
                ResultType r => [$"a.err.code == b.err.code && (a.err.code != 0 ? {Equal(r.Error, "a.err", "b.err")} : {Equal(r.Value, "a.value", "b.value")})"],
                StructSymbol s => s.Fields.Select(f => Equal(f.Type, "a." + FieldName(f.Name), "b." + FieldName(f.Name))).ToList(),
                TupleType tt => tt.Fields.Select((f, i) => Equal(f.Type, $"a.item{i + 1}", $"b.item{i + 1}")).ToList(),
                _ => throw new InvalidOperationException($"no equality for {t.DisplayName}"),
            };
            return "{\n    return " + (tests.Count == 0 ? "true" : string.Join("\n        && ", tests)) + ";\n}\n";
        });
        return $"{name}({a}, {b})";
    }

    /// <summary>The hash of a key: seeded FNV-1a over a scalar's bytes, a string's text or a symbol's ID; a tuple or struct
    /// folds its parts' hashes in declaration order, so padding never takes part (Q377).</summary>
    private string KeyHash(TypeSymbol key)
    {
        _hashes = true;
        var name = "bynh_hash_" + Key(key);
        return Helper(name, $"static uint64_t {name}({CType(key)} k)", () =>
        {
            List<(TypeSymbol Type, string Expr)>? parts = key switch
            {
                StructSymbol s => s.Fields.Select(f => (f.Type, "k." + FieldName(f.Name))).ToList(),
                TupleType tt => tt.Fields.Select((f, i) => (f.Type, $"k.item{i + 1}")).ToList(),
                _ => null,
            };
            if (parts is null)
                return key.IsString ? "{\n    return byn_hash_bytes(k.ptr, k.len);\n}\n"
                    : key == BuiltinType.Symbol ? "{\n    return byn_hash_bytes(&k.id, (int64_t)sizeof k.id);\n}\n"
                    : "{\n    return byn_hash_bytes(&k, (int64_t)sizeof k);\n}\n";
            var sb = new StringBuilder("{\n    uint64_t h = byn_hash_bytes(NULL, 0);\n");
            foreach (var (type, expr) in parts)
                sb.Append($"    h = byn_hash_mix(h, {KeyHash(type)}({expr}));\n");
            return sb.Append("    return h;\n}\n").ToString();
        });
    }

    /// <summary>Key equality through pointers, for <c>byn_map_*</c>.</summary>
    private string KeyEq(TypeSymbol key)
    {
        var ct = CType(key);
        var name = "bynh_keq_" + Key(key);
        return Helper(name, $"static bool {name}(const void* a, const void* b)", () =>
            $"{{\n    return {Equal(key, $"*(const {ct}*)a", $"*(const {ct}*)b")};\n}}\n");
    }

    /// <summary>Index, <c>slot</c>, <c>tryGet</c>, <c>contains</c> and <c>remove</c> of <paramref name="t"/>; <paramref name="map"/> is an lvalue for the mutating ones.</summary>
    internal string MapMethod(BuiltinMember member, MapType t, string map, string[] args, string loc)
    {
        var mt = CType(t);
        var kt = CType(t.KeyType);
        var vt = CType(t.ValueType);
        var hash = KeyHash(t.KeyType);
        var eq = KeyEq(t.KeyType);
        var find = $"byn_map_find(&m.h, m.keys, (int64_t)sizeof({kt}), &k, {hash}(k), {eq})";
        switch (member)
        {
            case BuiltinMember.MapIndexSet or BuiltinMember.MapSlot:
            {
                // A missing key is inserted with `d`: zero for a write target, the value type's default for `slot`.
                var name = "bynh_slot_" + Key(t);
                Helper(name, $"static {vt}* {name}({mt}* m, {kt} k, {vt} d)", () =>
                    $"{{\n    if (!m->h.alloc) m->h.alloc = byn_context;\n    bool added;\n" +
                    $"    int64_t i = byn_map_insert(&m->h, (void**)&m->keys, (int64_t)sizeof({kt}), (void**)&m->vals, (int64_t)sizeof({vt}), &k, {hash}(k), {eq}, &added);\n" +
                    "    if (added) {\n        m->keys[i] = k;\n        m->vals[i] = d;\n    }\n    return &m->vals[i];\n}\n");
                return $"(*{name}(&{map}, {args[0]}, {(member == BuiltinMember.MapSlot ? args[1] : $"(({vt}){{0}})")}))";
            }
            case BuiltinMember.MapIndex:
            {
                var name = "bynh_index_" + Key(t);
                Helper(name, $"static {vt} {name}({mt} m, {kt} k, const char* file, int line)", () =>
                    $"{{\n    int64_t i = {find};\n    if (i < 0) byn_panic(\"key not found in map\", file, line);\n    return m.vals[i];\n}}\n");
                return $"{name}({map}, {args[0]}, {loc})";
            }
            case BuiltinMember.MapTryGet:
            {
                var opt = CType(new OptionalType(t.ValueType));
                var name = "bynh_try_get_" + Key(t);
                Helper(name, $"static {opt} {name}({mt} m, {kt} k)", () =>
                    $"{{\n    int64_t i = {find};\n    return i < 0 ? ({opt}){{0}} : ({opt}){{true, m.vals[i]}};\n}}\n");
                return $"{name}({map}, {args[0]})";
            }
            case BuiltinMember.MapContains:
            {
                var name = "bynh_has_" + Key(t);
                Helper(name, $"static bool {name}({mt} m, {kt} k)", () => $"{{\n    return {find} >= 0;\n}}\n");
                return $"{name}({map}, {args[0]})";
            }
            default:
            {
                var name = "bynh_remove_" + Key(t);
                Helper(name, $"static bool {name}({mt}* m, {kt} k)", () =>
                    $"{{\n    return byn_map_remove(&m->h, m->keys, (int64_t)sizeof({kt}), &k, {hash}(k), {eq});\n}}\n");
                return $"{name}(&{map}, {args[0]})";
            }
        }
    }

    /// <summary>A statement that writes <paramref name="v"/> to the writer <c>w</c>.</summary>
    internal string Format(TypeSymbol t, string v, string w)
    {
        switch (t)
        {
            case PrimitiveType p:
                return p.Kind switch
                {
                    PrimitiveKind.String => $"byn_w_str({w}, {v});",
                    PrimitiveKind.F64 => $"byn_w_f64({w}, {v});",
                    PrimitiveKind.F32 => $"byn_w_f32({w}, {v});",
                    PrimitiveKind.Bool => $"byn_w_bool({w}, {v});",
                    PrimitiveKind.Char => $"byn_w_char({w}, {v});",
                    _ when p.IsSignedInteger => $"byn_w_i64({w}, (int64_t)({v}));",
                    _ => $"byn_w_u64({w}, (uint64_t)({v}));",
                };
            case ErrorSetSymbol or ErrorUnionType:
                return $"byn_w_error({w}, {v}.code);";
            case EnumSymbol e:
                return $"byn_w_str({w}, {EnumNames(e)}[{v}]);";
            case BuiltinType { Kind: BuiltinKind.Symbol }:
                return $"byn_w_str({w}, {SymbolText(v)});";
            case OwnedType o:
                return Format(o.Inner, $"(*{v})", w);
        }
        var ct = CType(t);
        var name = "bynh_fmt_" + Key(t);
        Helper(name, $"static void {name}(byn_writer* w, {ct} v)", () =>
        {
            var sb = new StringBuilder("{\n");
            void Text(string s) => sb.Append($"    byn_w_str(w, {StringLiteral(s)});\n");
            switch (t)
            {
                case OptionalType o:
                    sb.Append($"    if (v.has) {Format(o.Inner, "v.value", "w")}\n");
                    sb.Append("    else byn_w_str(w, BYN_STR(\"null\", 4));\n");
                    break;
                case ResultType r:
                    sb.Append($"    if (v.err.code) byn_w_error(w, v.err.code);\n    else {Format(r.Value, "v.value", "w")}\n");
                    break;
                case StructSymbol s when FormatInto(s) is { } method:
                    sb.Append($"    {FunctionName(method)}(&v, w{(method.Parameters.Count == 2 ? ", " + NoFormatSpec : "")});\n");
                    break;
                case UnionSymbol u:
                    sb.Append("    switch (v.tag) {\n");
                    foreach (var variant in u.Variants)
                    {
                        sb.Append($"    case {variant.Tag}:\n");
                        Text(variant.Fields.Count == 0 ? variant.Name : variant.Name + "(");
                        for (var i = 0; i < variant.Fields.Count; i++)
                        {
                            var f = variant.Fields[i];
                            Text((i > 0 ? ", " : "") + f.Name + ": ");
                            sb.Append("    ").Append(Format(f.Type, $"v.u.{FieldName(variant.Name)}.{FieldName(f.Name)}", "w")).Append('\n');
                        }
                        if (variant.Fields.Count > 0) Text(")");
                        sb.Append("        break;\n");
                    }
                    sb.Append("    }\n");
                    break;
                case TupleType tt:
                    Text("(");
                    for (var i = 0; i < tt.Fields.Count; i++)
                    {
                        if (i > 0) Text(", ");
                        sb.Append("    ").Append(Format(tt.Fields[i].Type, $"v.item{i + 1}", "w")).Append('\n');
                    }
                    Text(")");
                    break;
                case MapType m:
                    sb.Append("    byn_w_str(w, BYN_STR(\"{\", 1));\n    bool first = true;\n");
                    sb.Append("    for (int64_t i = 0; i < v.h.len; i++) {\n        if (v.h.dead[i]) continue;\n");
                    sb.Append("        if (!first) byn_w_str(w, BYN_STR(\", \", 2));\n        first = false;\n");
                    sb.Append("        ").Append(Format(m.KeyType, "v.keys[i]", "w")).Append('\n');
                    sb.Append("        byn_w_str(w, BYN_STR(\": \", 2));\n");
                    sb.Append("        ").Append(Format(m.ValueType, "v.vals[i]", "w")).Append("\n    }\n");
                    Text("}");
                    break;
                default:
                    throw new InvalidOperationException($"cannot format {t.DisplayName}");
            }
            return sb.Append("}\n").ToString();
        });
        return $"{name}({w}, {v});";
    }

    /// <summary>A struct's <c>formatInto(ref StrBuf)</c>, or else its <c>formatInto(ref StrBuf, as FormatSpec)</c>: the form a hole without specs calls.</summary>
    internal static FunctionSymbol? FormatInto(StructSymbol s) =>
        s.Methods.Where(m => m.Name == "formatInto" && !m.IsStatic && !m.Fails && m.Parameters.Count is 1 or 2
            && m.Parameters[0] is { IsByRef: true, Type: BuiltinType { Kind: BuiltinKind.StrBuf } }
            && (m.Parameters.Count == 1 || m.Parameters[1] is { IsByRef: false, Type: BuiltinType { Kind: BuiltinKind.FormatSpec } }))
            .OrderBy(m => m.Parameters.Count).FirstOrDefault();

    /// <summary>A struct's <c>formatInto(ref StrBuf, as FormatSpec)</c>: the form a hole with specs calls, as the binder's <c>TakesFormatSpec</c> assumes.</summary>
    internal static FunctionSymbol? FormatIntoWithSpec(StructSymbol s) =>
        s.Methods.FirstOrDefault(m => m.Name == "formatInto" && !m.IsStatic && !m.Fails && m.Parameters.Count == 2
            && m.Parameters[0] is { IsByRef: true, Type: BuiltinType { Kind: BuiltinKind.StrBuf } }
            && m.Parameters[1] is { IsByRef: false, Type: BuiltinType { Kind: BuiltinKind.FormatSpec } });

    /// <summary>The spec a struct's two-parameter <c>formatInto</c> receives outside a hole with specs: none given.</summary>
    internal const string NoFormatSpec = "((byn_format_spec){2, false, 0, ' ', 0, -1})";

    // ── Static data ──────────────────────────────────────────────────────────────

    /// <summary>Registers a file-scope table once.</summary>
    private string Static(string name, Func<string> decl)
    {
        if (_statics.ContainsKey(name)) return name;
        _statics[name] = "";
        _staticOrder.Add(name);
        _statics[name] = decl();
        return name;
    }

    /// <summary>The table of member names of <paramref name="e"/>, indexed by ordinal.</summary>
    internal string EnumNames(EnumSymbol e) => Static(CType(e) + "_names", () =>
        $"static const byn_str {CType(e)}_names[] = {{\n" + string.Concat(e.Members.Select(m => $"    {StringLiteral(m.Name)},\n")) + "};\n\n");

    /// <summary>Every member of <paramref name="e"/> in order, for <c>values</c>.</summary>
    internal string EnumValues(EnumSymbol e) => Static(CType(e) + "_values", () =>
        $"static const {CType(e)} {CType(e)}_values[] = {{{string.Join(", ", e.Members.Select(m => m.Ordinal))}}};\n\n");

    /// <summary>The values of field <paramref name="f"/> of a data enum, indexed by ordinal.</summary>
    internal string EnumField(EnumFieldSymbol f) => Static($"{CType(f.Enum)}_f_{f.Name}", () =>
        $"static const {CType(f.Type)} {CType(f.Enum)}_f_{f.Name}[] = {{\n"
        + string.Concat(f.Enum.Members.Select(m => $"    {Constant(m.Values[f.Index]!, f.Type)},\n")) + "};\n\n");

    /// <summary>A <c>const T[N]</c>, read in place: <c>(*(T*)&amp;name)</c>.</summary>
    internal string StaticArray(ConstSymbol c)
    {
        var at = CType(c.Type);
        var element = ((ArrayType)c.Type).Element;
        var name = Static($"byn_{c.Module.CName}__{c.Name}", () =>
        {
            var sb = new StringBuilder($"static const {at} byn_{c.Module.CName}__{c.Name} = {{{{");
            for (var i = 0; i < c.Elements.Length; i++)
            {
                if (i % 8 == 0) sb.Append("\n   ");
                sb.Append(' ').Append(Constant(c.Elements[i], element)).Append(',');
            }
            return sb.Append("\n}};\n\n").ToString();
        });
        return $"(*({at}*)&{name})";
    }

    // ── Literals ─────────────────────────────────────────────────────────────────

    internal static string CString(string s) => "\"" + Escape(Encoding.UTF8.GetBytes(s)) + "\"";

    internal static string StringLiteral(string s)
    {
        var bytes = Encoding.UTF8.GetBytes(s);
        return $"BYN_STR(\"{Escape(bytes)}\", {bytes.Length})";
    }

    private static string Escape(byte[] bytes)
    {
        var sb = new StringBuilder();
        foreach (var b in bytes)
        {
            if (b is >= 0x20 and < 0x7F && b != '"' && b != '\\' && b != '?') sb.Append((char)b);
            else sb.Append('\\').Append(Convert.ToString(b, 8).PadLeft(3, '0'));
        }
        return sb.ToString();
    }

    internal string Constant(ConstantValue c, TypeSymbol type)
    {
        switch (c.Value)
        {
            case bool b:
                return b ? "true" : "false";
            case string s:
                return StringLiteral(s);
            case Rune r:
                return $"UINT32_C({r.Value})";
            case double d:
                return FloatLiteral(d, type == PrimitiveType.F32);
            case Int128 i when type.IsFloat:
                return FloatLiteral((double)i, type == PrimitiveType.F32);
            case Int128 i:
                return type is PrimitiveType p ? p.Kind switch
                {
                    PrimitiveKind.I64 or PrimitiveKind.Isize => i == long.MinValue ? "INT64_MIN" : $"INT64_C({i})",
                    PrimitiveKind.U64 or PrimitiveKind.Usize => $"UINT64_C({i})",
                    _ => $"(({CType(p)}){i})",
                } : $"(({CType(type)}){i})";
            default:
                throw new InvalidOperationException($"unexpected constant {c.Value}");
        }
    }

    private static string FloatLiteral(double d, bool single)
    {
        if (double.IsNaN(d)) return single ? "((float)NAN)" : "((double)NAN)";
        if (double.IsInfinity(d)) return (d < 0 ? "(-" : "(") + (single ? "(float)INFINITY)" : "(double)INFINITY)");
        var text = d.ToString("R", CultureInfo.InvariantCulture);
        if (!text.Contains('.') && !text.Contains('E')) text += ".0";
        return single ? $"((float){text})" : $"({text})";
    }
}

/// <summary>Emits one function body.</summary>
internal sealed class FunctionEmitter
{
    private readonly CEmitter _c;
    private readonly LoweredFunction _f;
    private readonly FunctionSymbol _fn;
    private readonly Dictionary<LocalSymbol, string> _names = new();
    private readonly StringBuilder _sb = new();
    private readonly string _file;
    // `#line` maps the C of each statement back to this file (a C string literal); null when the function has no file.
    private readonly string? _linePath;
    // The line of the last `#line` written and the output length after it; a repeat with no C between is skipped.
    private int _lastLine;
    private int _lastLineEnd;
    private int _indent = 1;
    // Ownership checks: the statement being emitted is first emitted dry to find locals it both reads and moves,
    // whose C evaluation order is unspecified, so their moved slots are not set there.
    private HashSet<LocalSymbol>? _reads;
    private HashSet<LocalSymbol>? _moves;
    private HashSet<LocalSymbol> _unsequenced = [];
    // The locals the statement being emitted moves (from the dry run).
    private HashSet<LocalSymbol> _moved = [];
    // Ownership checks: claims for the owned places the statement being emitted passes by pointer (ref, out, a method's
    // receiver), run once it is done, so storage the callee allocated through the pointer has its owner.
    private List<string> _afterCalls = [];

    public FunctionEmitter(CEmitter c, LoweredFunction f)
    {
        _c = c;
        _f = f;
        _fn = f.Symbol;
        _file = c.FileName(_fn);
        _linePath = _fn.File is null ? null : CEmitter.CString(c.FilePath(_fn));
        foreach (var p in _fn.Parameters) _names[p] = "p_" + p.Name;
        // A lambda reads each capture from its environment tuple (spec 007 R13).
        if (_fn.Captures.Count > 0)
        {
            var env = c.CType(new TupleType(_fn.Captures.Select(l => new TupleField(null, l.Type)).ToArray()));
            for (var i = 0; i < _fn.Captures.Count; i++) _names[_fn.Captures[i]] = $"(({env}*)env)->item{i + 1}";
        }
        var n = 0;
        foreach (var l in f.Locals)
            _names[l] = l.Kind == LocalKind.Temp ? "t" + n++ : "l" + n++ + "_" + l.Name;
    }

    private bool ReturnsValue => !_fn.ReturnType.IsVoid && !_fn.ReturnType.IsNever && _fn.Kind != FunctionKind.Constructor;

    public string Signature()
    {
        string result;
        if (_fn.Fails) result = _c.ErrorCType;
        else if (_fn.Kind == FunctionKind.Constructor) result = _c.CType(_fn.Owner!);
        else result = _c.CType(_fn.ReturnType);
        var ps = new List<string>();
        if (_fn.Kind == FunctionKind.Lambda) ps.Add("void* env");
        if (_fn.HasThis && _fn.Kind != FunctionKind.Constructor) ps.Add($"{_c.CType(_fn.Owner!)}* self");
        foreach (var p in _fn.Parameters) ps.Add($"{_c.CType(p.Type)}{(p.IsByRef ? "*" : "")} {_names[p]}");
        if (_fn.Fails && ReturnsValue) ps.Add($"{_c.CType(_fn.ReturnType)}* byn_out");
        var noreturn = _fn.ReturnType.IsNever && !_fn.Fails ? "BYN_NORETURN " : "";
        return $"{noreturn}{result} {_c.FunctionName(_fn)}({(ps.Count == 0 ? "void" : string.Join(", ", ps))})";
    }

    public string Emit()
    {
        _sb.Append(Signature()).Append(" {\n");
        if (_fn.Kind == FunctionKind.Constructor)
        {
            var t = _c.CType(_fn.Owner!);
            Line($"{t} self_v = {{0}};");
            Line($"{t}* self = &self_v;");
        }
        foreach (var l in _f.Locals)
        {
            if (l.Type.IsVoid || l.Type.IsNever) continue;
            Line($"{_c.CType(l.Type)} {_names[l]} = {{0}};");
        }
        foreach (var l in _fn.Parameters.Concat<LocalSymbol>(_f.Locals))
            if (HasSlot(l)) Line($"byn_own_slot {Slot(l)} = {{0}};");
        for (var i = 0; i < _f.ContextSlots; i++) Line($"byn_alloc* ctx{i} = byn_context;");
        for (var i = 0; i < _f.PanicSlots; i++) Line($"byn_panic_handler ph{i};");
        if (_fn is { Kind: FunctionKind.Lambda, Captures.Count: 0 }) Line("(void)env;");
        foreach (var s in _f.Body.Statements) Statement(s);
        if (_fn.Kind == FunctionKind.Constructor) Line("return self_v;");
        else if (_fn.Fails && !ReturnsValue) Line($"return ({_c.ErrorCType}){{0}};");
        else if (_fn.ReturnType.IsNever) Line($"byn_unreachable({_file}, {LineOf(_f.Body.Syntax)});");
        _sb.Append("}\n");
        if (_lastLine != 0) _sb.Append(CEmitter.ResetLine).Append('\n');
        return _sb.ToString();
    }

    private void Line(string text) => _sb.Append(' ', _indent * 4).Append(text).Append('\n');

    private int LineOf(Node syntax) => _fn.File is { } f ? f.Source.GetLinePosition(syntax.Span.Start).Line : 0;

    private string Loc(Node syntax) => $"{_file}, {LineOf(syntax)}";

    /// <summary><c>#line N "file.byn"</c>, so debuggers and C compiler messages name the Bayan line of the code that follows.</summary>
    private void MapLine(Node syntax)
    {
        if (_linePath is null) return;
        var line = LineOf(syntax);
        if (line == _lastLine && _sb.Length == _lastLineEnd) return;
        _lastLine = line;
        _sb.Append("#line ").Append(line).Append(' ').Append(_linePath).Append('\n');
        _lastLineEnd = _sb.Length;
    }

    // ── Ownership checks ─────────────────────────────────────────────────────────

    /// <summary>A local, owning pattern binding (of <c>switch move x</c>) or <c>move</c> parameter this function owns.</summary>
    private static bool IsOwner(LocalSymbol l) =>
        l is { Kind: LocalKind.Let or LocalKind.Var or LocalKind.PatternVariable, BorrowsSubject: false } or ParameterSymbol { Modifier: ParamModifier.Move };

    /// <summary>Whether <paramref name="l"/> has a moved slot: an owned local of a unique type.</summary>
    private bool HasSlot(LocalSymbol l) => _c.OwnershipChecks && IsOwner(l) && Bayan.Semantics.TypeFacts.IsUnique(l.Type);

    private string Slot(LocalSymbol l) => "own_" + _names[l];

    /// <summary>The owned local <paramref name="e"/> lives in by value (through fields and tuple items), or null.</summary>
    private static LocalSymbol? OwnerRoot(BoundExpr e) => e switch
    {
        BoundLocal l when IsOwner(l.Local) => l.Local,
        BoundField f => OwnerRoot(f.Receiver),
        BoundTupleElement t => OwnerRoot(t.Receiver),
        _ => null,
    };

    /// <summary>The local <paramref name="e"/> lives in by value, or null.</summary>
    private static LocalSymbol? Root(BoundExpr e) => e switch
    {
        BoundLocal l => l.Local,
        BoundField f => Root(f.Receiver),
        BoundTupleElement t => Root(t.Receiver),
        _ => null,
    };

    /// <summary>A store target as an lvalue, without checking its local was not moved.</summary>
    private string Place(BoundExpr e) => e switch
    {
        BoundLocal l => l.Local is ParameterSymbol { IsByRef: true } ? $"(*{_names[l.Local]})" : _names[l.Local],
        BoundField f => $"{Place(f.Receiver)}.{CEmitter.FieldName(f.Field.Name)}",
        BoundTupleElement t => $"{Place(t.Receiver)}.item{t.Index + 1}",
        _ => Expr(e),
    };

    /// <summary><c>target = value</c> through the checker, or null when it needs no hook (temporaries, storage-free types).
    /// Without <paramref name="claim"/> an owned target does not own the value yet (a pattern binding, see <see cref="LClaim"/>).</summary>
    private string? CheckedStore(BoundExpr target, BoundExpr value, bool claim = true)
    {
        if (!_c.OwnershipChecks) return null;
        var root = Root(target);
        var slot = target is BoundLocal { Local: var l } && HasSlot(l);
        if (root is { Kind: LocalKind.Temp } || (!slot && !CEmitter.OwnsStorage(target.Type))) return null;
        var claims = claim && root is not null && IsOwner(root) ? "true" : "false";
        return $"{_c.OwnSet(target.Type)}(&{Place(target)}, {Expr(value)}, {(slot ? "&" + Slot(((BoundLocal)target).Local) : "NULL")}, {claims}, {Loc(target.Syntax)})";
    }

    /// <summary>A mutation of <paramref name="receiver"/> that may allocate; an owned receiver then owns the storage.</summary>
    private string Claimed(string call, BoundExpr receiver, Node syntax) =>
        _c.OwnershipChecks && OwnerRoot(receiver) is not null ? $"({call}, {_c.OwnClaim(receiver.Type)}(&{Place(receiver)}, {Loc(syntax)}))" : call;

    /// <summary>After the call, an owned <paramref name="place"/> passed by pointer owns its storage, unless the
    /// statement moves it (the moved-to owner has the storage by then).</summary>
    private void ClaimAfterCall(BoundExpr place, Node syntax)
    {
        if (_c.OwnershipChecks && OwnerRoot(place) is { } root && !_moved.Contains(root) && CEmitter.OwnsStorage(place.Type))
            _afterCalls.Add($"{_c.OwnClaim(place.Type)}(&{Place(place)}, {Loc(syntax)});");
    }

    private void ClaimMapEntry(BoundAssign a)
    {
        if (_c.OwnershipChecks && a.Target is BoundBuiltinCall { Member: BuiltinMember.MapIndexSet or BuiltinMember.MapSlot, Receiver: { } map }
            && OwnerRoot(map) is not null)
            Line($"{_c.OwnClaim(map.Type)}(&{Place(map)}, {Loc(a.Syntax)});");
    }

    /// <summary>Emits <paramref name="s"/> (or an if's condition) dry to find the locals it both reads and moves.</summary>
    private void FindUnsequenced(BoundStmt s)
    {
        _unsequenced = [];
        _reads = [];
        _moves = [];
        var mark = _sb.Length;
        var (lastLine, lastLineEnd) = (_lastLine, _lastLineEnd);
        if (s is BoundIf i) Expr(i.Condition);
        else Statement(s);
        _sb.Length = mark;
        (_lastLine, _lastLineEnd) = (lastLine, lastLineEnd);
        _moved = _moves;
        _reads.IntersectWith(_moves);
        _unsequenced = _reads;
        _reads = _moves = null;
    }

    // ── Statements ───────────────────────────────────────────────────────────────

    private void Block(BoundStmt s)
    {
        _indent++;
        if (s is BoundBlock b) foreach (var inner in b.Statements) Statement(inner);
        else Statement(s);
        _indent--;
    }

    private void Statement(BoundStmt s)
    {
        if (_c.OwnershipChecks && _reads is null && s is not (BoundBlock or LLoop or LLabel or LGoto or LPushPanicHandler)) FindUnsequenced(s);
        _afterCalls = [];
        var mark = _sb.Length;
        var (lastLine, lastLineEnd) = (_lastLine, _lastLineEnd);
        if (s is not (BoundBlock or LLabel)) MapLine(s.Syntax);
        var start = _sb.Length;
        switch (s)
        {
            case BoundBlock b:
                Line("{");
                Block(b);
                Line("}");
                break;
            case BoundExprStmt e:
                Line($"(void){Expr(e.Expr)};");
                break;
            case BoundAssign a when a.Op is null && CheckedStore(a.Target, a.Value) is { } store:
                Line($"(void){store};");
                ClaimMapEntry(a);
                break;
            case BoundAssign a:
                Line($"{Expr(a.Target)} = {Expr(a.Value)};");
                ClaimMapEntry(a);
                break;
            case BoundIf i:
            {
                Line($"if ({Expr(i.Condition)}) {{");
                var after = _afterCalls;
                _afterCalls = [];
                AfterCalls(after);
                Block(i.Then);
                if (i.Else is not null || after.Count > 0)
                {
                    Line("} else {");
                    AfterCalls(after);
                    if (i.Else is not null) Block(i.Else);
                }
                Line("}");
                break;
            }
            case LLoop l:
                Line("for (;;) {");
                Block(l.Body);
                Line("}");
                break;
            case LLabel l:
                _sb.Append(' ', Math.Max(0, _indent - 1) * 4).Append(l.Name).Append(":;\n");
                break;
            case LGoto g:
                Line($"goto {g.Label};");
                break;
            case LReturn r:
                Return(r);
                _afterCalls = [];
                break;
            case LReturnError e:
                Line($"return {Expr(e.Code)};");
                break;
            case LFailingCall f:
            {
                var result = f.Result is null ? null : "&" + _names[f.Result];
                // Built-in failing calls return the runtime's bare code, except the ones whose errors carry a payload.
                var call = Call(f.Call, result);
                Line(f.Call.Function.Builtin is BuiltinFunction.None or BuiltinFunction.Utf8Decode or BuiltinFunction.HexDecode or BuiltinFunction.IntParse
                    ? $"{_names[f.Error]} = {call};"
                    : $"{_names[f.Error]} = ({_c.ErrorCType}){{ .code = {call} }};");
                break;
            }
            case LWrite w:
                Write(w);
                break;
            case LPanic p:
                Line($"byn_panic({CEmitter.CString(p.Message)}, {Loc(p.Syntax)});");
                break;
            case LSetContext c when c.Arena is { } arena:
                Line($"ctx{c.Slot} = byn_context;");
                Line($"byn_context = byn_arena_alloc({Expr(arena)});");
                break;
            case LSetContext c:
                Line($"byn_context = ctx{c.Slot};");
                break;
            case LFreeArena f:
                Line($"byn_arena_free({Expr(f.Arena)});");
                break;
            case LPushPanicHandler p:
                // The runtime longjmps here on a panic; the handler reads only `let`s and parameters, unchanged since the setjmp.
                Line($"if (BYN_PANIC_CATCH(&ph{p.Slot})) {{");
                _indent++;
                if (p.Panic is not null) Line($"{_names[p.Panic]} = byn_panic_current();");
                _indent--;
                Block(p.Body);
                _indent++;
                Line("byn_panic_resume();");
                _indent--;
                Line("}");
                Line($"byn_panic_push(&ph{p.Slot});");
                break;
            case LPopPanicHandler p:
                Line($"byn_panic_pop(&ph{p.Slot});");
                break;
            case BoundSetOnPanic o:
                Line($"byn_on_panic = {_c.FunctionName(o.Handler)};");
                break;
            case LClaim c:
                if (_c.OwnershipChecks && IsOwner(c.Local) && CEmitter.OwnsStorage(c.Local.Type))
                    Line($"{_c.OwnClaim(c.Local.Type)}(&{_names[c.Local]}, {Loc(c.Syntax)});");
                break;
            default:
                throw new InvalidOperationException($"cannot emit {s.GetType().Name}");
        }
        foreach (var c in _afterCalls) Line(c);
        _afterCalls = [];
        // A statement with no C (a claim without ownership checks) keeps no `#line` either.
        if (_sb.Length == start)
        {
            _sb.Length = mark;
            (_lastLine, _lastLineEnd) = (lastLine, lastLineEnd);
        }
    }

    /// <summary>The claims after an if's condition, at the start of a branch.</summary>
    private void AfterCalls(List<string> claims)
    {
        _indent++;
        foreach (var c in claims) Line(c);
        _indent--;
    }

    /// <summary>One hit of a coverage counter (a <c>--coverage</c> build).</summary>
    private static string Count(LCount c) => $"byn_cov[{c.Id.ToString(CultureInfo.InvariantCulture)}]++";

    private void Return(LReturn r)
    {
        if (_fn.Kind == FunctionKind.Constructor)
        {
            Line("return self_v;");
            return;
        }
        if (_fn.Fails)
        {
            if (r.Value is not null) Line($"*byn_out = {Returned(r.Value)};");
            Line($"return ({_c.ErrorCType}){{0}};");
            return;
        }
        Line(r.Value is null ? "return;" : $"return {Returned(r.Value)};");
    }

    private string Returned(BoundExpr value) =>
        _c.OwnershipChecks && CEmitter.OwnsStorage(value.Type) ? $"{_c.OwnReturn(value.Type)}({Expr(value)})" : Expr(value);

    private void Write(LWrite w)
    {
        Line("{");
        _indent++;
        if (w.Sink == WriteSink.StrBuf)
        {
            Line($"byn_writer* w = &{Expr(w.Target!)};");
            Line($"w->file = {_file};");
            Line($"w->line = {LineOf(w.Syntax)};");
        }
        else
        {
            var mode = w.Sink == WriteSink.Print ? $"{Expr(w.Target!)} == 1 ? BYN_WRITE_STDERR : BYN_WRITE_STDOUT" : "BYN_WRITE_TRUNCATE";
            // A panic message keeps as much as the runtime does (`byn_panic_text`), room for an `assert` diagram; a log line never allocates, so it is cut.
            var size = w.Sink switch { WriteSink.Panic => 1024, WriteSink.Log => 512, _ => 256 };
            Line($"uint8_t wb[{size}];");
            Line($"byn_writer wv = {{wb, {size}, 0, {mode}, {Loc(w.Syntax)}}};");
            Line("byn_writer* w = &wv;");
        }
        for (var i = 0; i < w.Parts.Length; i++)
        {
            var part = w.Parts[i];
            var write = part.Text is { Length: > 0 } text ? $"byn_w_str(w, {CEmitter.StringLiteral(text)});"
                : part.Value is { } value ? part.Spec is { } spec ? FormatWithSpec(value, spec) : _c.Format(value.Type, Expr(value), "w") : null;
            if (write is null) continue;
            Line(w.Guards?[i] is { } guard ? $"if ({Expr(guard)}) {{ {write} }}" : write);
        }
        if (_c.OwnershipChecks && w.Sink == WriteSink.StrBuf && OwnerRoot(w.Target!) is not null) Line($"{_c.OwnClaim(w.Target!.Type)}(w, {Loc(w.Syntax)});");
        if (w.Sink == WriteSink.Print) Line("byn_w_println(w);");
        else if (w.Sink == WriteSink.Panic) Line($"byn_panic_str((byn_str){{wb, wv.len}}, {Loc(w.Syntax)});");
        else if (w.Sink == WriteSink.Log) Line($"byn_log({Expr(w.Target!)}, (byn_str){{wb, wv.len}});");
        _indent--;
        Line("}");
    }

    /// <summary>
    /// A hole with specs: the value is formatted into a stack buffer (a radix, fixed digits or the debug view),
    /// then written padded to the width in runes.
    /// </summary>
    private string FormatWithSpec(BoundExpr value, BoundFormatSpec spec)
    {
        var t = value.Type;
        var v = Expr(value);
        // A struct with a `formatInto` that takes the `FormatSpec` reads every spec itself, padding included, even when it also has the one-parameter form.
        if (t is StructSymbol s && CEmitter.FormatIntoWithSpec(s) is { } method)
            return $"{{ {_c.CType(t)} fv = {v}; {_c.FunctionName(method)}(&fv, w, (byn_format_spec){{{(spec.Radix switch { 2 => 0, 8 => 1, 16 => 3, _ => 2 })}, "
                + $"{(spec.Debug ? "true" : "false")}, {spec.Width}, {spec.Fill}u, {Math.Max(spec.Align, 0)}, {spec.Digits}}}); }}";
        string Inner(string sw) => spec.Radix != 0
            ? $"bynh_w_radix({sw}, (uint64_t)({v}), {(t.IsSignedInteger ? $"({v}) < 0" : "false")}, {spec.Radix});"
            : spec.Digits >= 0 ? $"bynh_w_digits({sw}, (double)({v}), {spec.Digits});"
            : spec.Debug ? Debug(t, v, sw)
            : _c.Format(t, v, sw);
        if (spec.Radix != 0)
            _c.Helper("bynh_w_radix", "static void bynh_w_radix(byn_writer* w, uint64_t v, bool negative, int base)", () =>
                "{\n    uint8_t d[64];\n    int n = 0;\n    if (negative) {\n        byn_w_char(w, '-');\n        v = 0 - v;\n    }\n"
                + "    do {\n        d[n++] = (uint8_t)\"0123456789abcdef\"[v % (uint64_t)base];\n        v /= (uint64_t)base;\n    } while (v > 0);\n"
                + "    while (n > 0) byn_w_bytes(w, &d[--n], 1);\n}\n");
        if (spec.Digits >= 0)
            // Rounds half away from zero; a value too large to scale is written as `byn_w_f64` writes it.
            _c.Helper("bynh_w_digits", "static void bynh_w_digits(byn_writer* w, double v, int digits)", () =>
                "{\n    double p = 1;\n    for (int i = 0; i < digits; i++) p *= 10;\n    double s = v * p;\n"
                + "    if (!(s > -9.0e15 && s < 9.0e15)) {\n        byn_w_f64(w, v);\n        return;\n    }\n"
                + "    int64_t n = (int64_t)(s < 0 ? s - 0.5 : s + 0.5);\n    if (n < 0 || (n == 0 && v < 0)) byn_w_char(w, '-');\n"
                + "    uint64_t m = n < 0 ? (uint64_t)-n : (uint64_t)n, q = (uint64_t)p;\n    byn_w_u64(w, m / q);\n    if (digits == 0) return;\n"
                + "    byn_w_char(w, '.');\n    uint64_t f = m % q;\n    for (uint64_t k = q / 10; k > 0; k /= 10) byn_w_char(w, (uint32_t)('0' + f / k % 10));\n}\n");
        if (spec.Width == 0) return Inner("w");
        // Numbers align to the end by default, everything else to the start.
        var align = spec.Align >= 0 ? spec.Align : t.IsNumeric ? 1 : 0;
        // The 1024-byte cut drops a code point it would split.
        var pad = _c.Helper("bynh_w_padded", "static void bynh_w_padded(byn_writer* w, byn_str s, int64_t width, uint32_t fill, int align)", () =>
            "{\n    if (s.len > 0) {\n        int64_t k = s.len - 1;\n        while (k > 0 && (s.ptr[k] & 0xC0) == 0x80) k--;\n"
            + "        uint8_t c = s.ptr[k];\n        int64_t need = c < 0x80 ? 1 : (c & 0xE0) == 0xC0 ? 2 : (c & 0xF0) == 0xE0 ? 3 : 4;\n"
            + "        if (k + need > s.len) s.len = k;\n    }\n    int64_t runes = 0;\n    for (int64_t i = 0; i < s.len; i++) runes += (s.ptr[i] & 0xC0) != 0x80;\n"
            + "    int64_t gap = width > runes ? width - runes : 0, before = align == 1 ? gap : align == 2 ? gap / 2 : 0;\n"
            + "    for (int64_t i = 0; i < before; i++) byn_w_char(w, fill);\n    byn_w_str(w, s);\n"
            + "    for (int64_t i = before; i < gap; i++) byn_w_char(w, fill);\n}\n");
        return $"{{ uint8_t sb[1024]; byn_writer sv = {{sb, 1024, 0, BYN_WRITE_TRUNCATE, {Loc(value.Syntax)}}}; byn_writer* sw = &sv; {Inner("sw")} "
            + $"{pad}(w, (byn_str){{sb, sv.len}}, {spec.Width}, {spec.Fill}u, {align}); }}";
    }

    /// <summary>
    /// The debug view (spec §13): strings, <c>Symbol</c>s and runes quoted, a struct in its literal form <c>P { x: 1, name: "a" }</c>
    /// (one whose <c>formatInto</c> takes the <c>FormatSpec</c> formats itself), everything else as it displays.
    /// </summary>
    private string Debug(TypeSymbol t, string v, string w)
    {
        if (t.IsString || t == BuiltinType.Symbol)
            return _c.Helper("bynh_w_quoted", "static void bynh_w_quoted(byn_writer* w, byn_str s, uint32_t quote)", () =>
                "{\n    byn_w_char(w, quote);\n    for (int64_t i = 0; i < s.len; i++) {\n"
                + "        uint8_t c = s.ptr[i];\n        if (c == quote || c == '\\\\') byn_w_char(w, '\\\\');\n"
                + "        if (c == '\\n') byn_w_str(w, (byn_str){(const uint8_t*)\"\\\\n\", 2});\n        else byn_w_bytes(w, &c, 1);\n    }\n    byn_w_char(w, quote);\n}\n") + $"({w}, {(t.IsString ? v : _c.SymbolText(v))}, '\"');";
        if (t is PrimitiveType { Kind: PrimitiveKind.Char })
            return _c.Helper("bynh_w_rune_quoted", "static void bynh_w_rune_quoted(byn_writer* w, uint32_t c)", () =>
                "{\n    byn_w_char(w, '\\'');\n    if (c == '\\'' || c == '\\\\') byn_w_char(w, '\\\\');\n"
                + "    if (c == '\\n') byn_w_str(w, (byn_str){(const uint8_t*)\"\\\\n\", 2});\n    else byn_w_char(w, c);\n    byn_w_char(w, '\\'');\n}\n") + $"({w}, {v});";
        if (t is not StructSymbol s || CEmitter.FormatInto(s) is { Parameters.Count: 2 }) return _c.Format(t, v, w);
        var name = _c.Helper("bynh_debug_" + _c.Key(t), $"static void bynh_debug_{_c.Key(t)}(byn_writer* w, {_c.CType(t)} v)", () =>
        {
            var sb = new StringBuilder("{\n");
            sb.Append($"    byn_w_str(w, {CEmitter.StringLiteral(s.DisplayName + (s.Fields.Count == 0 ? " {}" : " { "))});\n");
            for (var i = 0; i < s.Fields.Count; i++)
            {
                var f = s.Fields[i];
                sb.Append($"    byn_w_str(w, {CEmitter.StringLiteral((i == 0 ? "" : ", ") + f.Name + ": ")});\n");
                sb.Append("    ").Append(Debug(f.Type, "v." + CEmitter.FieldName(f.Name), "w")).Append('\n');
            }
            if (s.Fields.Count > 0) sb.Append($"    byn_w_str(w, {CEmitter.StringLiteral(" }")});\n");
            return sb.Append("}\n").ToString();
        });
        return $"{name}({w}, {v});";
    }

    // ── Expressions ──────────────────────────────────────────────────────────────

    private string Expr(BoundExpr e)
    {
        if (e.Constant is { } c && e.Type is PrimitiveType { IsVoid: false, IsNever: false } && e is not BoundLocal { Local: ParameterSymbol })
            return _c.Constant(c, e.Type);
        switch (e)
        {
            case BoundLiteral l:
                return _c.Constant(l.Value, l.Type);
            case BoundSymbolLiteral s:
                return _c.SymbolLiteral(s.Text);
            case BoundDefault d:
                return $"(({_c.CType(d.Type)}){{0}})";
            case BoundLocal l when HasSlot(l.Local):
                _reads?.Add(l.Local);
                return $"(*(byn_own_read(&{Slot(l.Local)}, {CEmitter.CString(l.Type.DisplayName)}, {Loc(l.Syntax)}), &{_names[l.Local]}))";
            case BoundLocal l:
                return l.Local is ParameterSymbol { IsByRef: true } ? $"(*{_names[l.Local]})" : _names[l.Local];
            case BoundThis:
                return "(*self)";
            case BoundMove { Operand: BoundLocal l } m when HasSlot(l.Local):
                _moves?.Add(l.Local);
                return $"(*{_c.OwnMove(l.Type)}(&{_names[l.Local]}, {(_unsequenced.Contains(l.Local) ? "NULL" : "&" + Slot(l.Local))}, {Loc(m.Syntax)}))";
            case BoundMove m:
                return Expr(m.Operand);
            case BoundField f:
                return $"{Expr(f.Receiver)}.{CEmitter.FieldName(f.Field.Name)}";
            case BoundTupleElement t:
                return $"{Expr(t.Receiver)}.item{t.Index + 1}";
            case BoundCall call:
                return Call(call, null);
            case BoundBuiltinCall b:
                return Builtin(b);
            case BoundUnary u:
                return Unary(u);
            case BoundBinary b:
                return Binary(b);
            case BoundConversion c2:
                return Conversion(c2);
            case BoundConditional c2:
                return $"({Expr(c2.Condition)} ? {Expr(c2.WhenTrue)} : {Expr(c2.WhenFalse)})";
            case BoundStructLiteral { State: { } state } s:
            {
                // A state literal: the fields in order, then the tag and the state's payload by name.
                var parts = s.Fields.Select(Expr).Append($".tag = {state.Tag}");
                if (s.Payload.Length > 0) parts = parts.Append($".u.{CEmitter.FieldName(state.Name)} = {{{string.Join(", ", s.Payload.Select(Expr))}}}");
                return $"(({_c.CType(s.Struct)}){{{string.Join(", ", parts)}}})";
            }
            case BoundStructLiteral s:
                return s.Fields.Length == 0 ? $"(({_c.CType(s.Struct)}){{0}})" : $"(({_c.CType(s.Struct)}){{{string.Join(", ", s.Fields.Select(Expr))}}})";
            case BoundTuple t:
                return $"(({_c.CType(t.Type)}){{{string.Join(", ", t.Elements.Select(Expr))}}})";
            case BoundUnionNew u:
                return u.Payload.Length == 0
                    ? $"(({_c.CType(u.Type)}){{.tag = {u.Variant.Tag}}})"
                    : $"(({_c.CType(u.Type)}){{.tag = {u.Variant.Tag}, .u.{CEmitter.FieldName(u.Variant.Name)} = {{{string.Join(", ", u.Payload.Select(Expr))}}}}})";
            case BoundCollection { Type: ListType l }:
                return $"(({_c.CType(l)}){{NULL, 0, 0, byn_context}})";
            case BoundCollection { Type: MapType m }:
                return $"(({_c.CType(m)}){{{{.alloc = byn_context}}, NULL, NULL}})";
            case BoundCollection { Type: ArrayType a } col:
                return col.Elements.Length == 0 ? $"(({_c.CType(a)}){{0}})" : $"(({_c.CType(a)}){{{{{string.Join(", ", col.Elements.Select(Expr))}}}}})";
            case BoundIndex i:
                return Index(i);
            case BoundSlice s:
                return Slice(s);
            case BoundErrorVariant v:
                return v.Payload.Length == 0
                    ? $"(({_c.ErrorCType}){{ .code = UINT32_C({v.Variant.Code}) }})"
                    : $"(({_c.ErrorCType}){{ .code = UINT32_C({v.Variant.Code}), .p.e{v.Variant.Code} = {{ {string.Join(", ", v.Payload.Select(Expr))} }} }})";
            case BoundEnumMember m:
                return $"(({_c.CType(m.Type)}){m.Member.Ordinal})";
            case BoundEnumValues v:
                return $"(({_c.CType(v.Type)}){{({_c.CType(v.Enum)}*){_c.EnumValues(v.Enum)}, {v.Enum.Members.Count}}})";
            case BoundStaticArray a:
                return _c.StaticArray(a.Const);
            case LOptionalHas h:
                return $"{Expr(h.Optional)}.has";
            case LUnionTag u:
                return $"{Expr(u.Union)}.tag";
            case LMutantIs m:
                return $"byn_mutant_is({m.Id.ToString(CultureInfo.InvariantCulture)})";
            case LCount count:
                return Count(count);
            case LErrorCode code:
                return $"{Expr(code.Error)}.code";
            case LErrorField f:
                return $"{Expr(f.Error)}.p.e{f.Variant.Code}.{CEmitter.FieldName(f.Variant.Fields[f.Index].Name)}";
            case LUnionField u:
                return $"{Expr(u.Union)}.u.{CEmitter.FieldName(u.Variant.Name)}.{CEmitter.FieldName(u.Variant.Fields[u.Index].Name)}";
            case LOptionalValue v:
                return $"{Expr(v.Optional)}.value";
            case LAssignExpr a:
                return CheckedStore(a.Target, a.Value, claim: false) ?? $"({Expr(a.Target)} = {Expr(a.Value)})";
            case LSequence s:
                return "(" + string.Join(", ", s.Effects.Select(Expr).Append(Expr(s.Value))) + ")";
            case LIndexUnchecked u:
                return u.Target.Type is ArrayType ? $"{Expr(u.Target)}.v[{Expr(u.Index)}]" : $"{Expr(u.Target)}.ptr[{Expr(u.Index)}]";
            case LNextChar n:
                return $"byn_str_next({Expr(n.Text)}, &{_names[n.Position]})";
            // A named function goes through a thunk taking the environment; a lambda takes it already.
            case LFunctionValue { Function.Kind: FunctionKind.Lambda } f:
                return $"(({_c.CType(f.Type)}){{{_c.FunctionName(f.Function)}, {(f.Env is null ? "NULL" : "&" + _names[f.Env])}}})";
            case LFunctionValue f:
                return $"(({_c.CType(f.Type)}){{{_c.FunctionThunk(f.Function, f.FunctionType)}, NULL}})";
            default:
                throw new InvalidOperationException($"cannot emit {e.GetType().Name}");
        }
    }

    private string Call(BoundCall c, string? result)
    {
        var fn = c.Function;
        var args = new List<string>();
        switch (fn.Builtin)
        {
            case BuiltinFunction.Print:
                return $"byn_print({Expr(c.Arguments[1])}, {Expr(c.Arguments[0])})";
            case BuiltinFunction.Log:
                return $"byn_log({Expr(c.Arguments[1])}, {Expr(c.Arguments[0])})";
            case BuiltinFunction.Panic:
                return $"byn_panic_str({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            case BuiltinFunction.Todo:
                return $"byn_todo_str({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            case BuiltinFunction.ArenaNew:
                return "byn_arena_new()";
            case BuiltinFunction.StrBufNew:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_strbuf", $"static byn_writer bynh_strbuf({span} s, const char* file, int line)", () =>
                    "{\n    return (byn_writer){s.ptr, s.len, 0, BYN_WRITE_STRICT, file, line};\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            }
            // `StrBuf.over(span)` writes into the span and spills to `context.allocator` when it is outgrown.
            case BuiltinFunction.StrBufOver:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_strbuf_over", $"static byn_writer bynh_strbuf_over({span} s, const char* file, int line)", () =>
                    "{\n    return (byn_writer){s.ptr, s.len, 0, BYN_WRITE_GROW, file, line, byn_context};\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            }
            case BuiltinFunction.StrBufGrow when c.Arguments.Length == 0:
                return "byn_strbuf_grow(byn_context)";
            case BuiltinFunction.StrBufGrow:
            {
                var name = _c.Helper("bynh_strbuf_capacity", "static byn_writer bynh_strbuf_capacity(int64_t n)", () =>
                    "{\n    byn_writer w = byn_strbuf_grow(byn_context);\n"
                    + "    if (n > 0) {\n        w.buf = (uint8_t*)byn_context->resize(byn_context, NULL, 0, n);\n        w.cap = n;\n    }\n    return w;\n}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.OwnedNew:
            {
                var inner = ((OwnedType)c.Type).Inner;
                var it = _c.CType(inner);
                var name = "bynh_own_" + _c.Key(inner);
                _c.Helper(name, $"static {it}* {name}({it} v)", () =>
                    $"{{\n    return ({it}*)byn_copy_bytes(&v, (int64_t)sizeof v, byn_context);\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.UntrustedNew or BuiltinFunction.Trust:
                return Expr(c.Arguments[0]);
            case BuiltinFunction.IoReadFile:
            {
                var list = _c.CType(fn.ReturnType);
                var name = _c.Helper("bynh_io_read_file", $"static uint32_t bynh_io_read_file(byn_str path, {list}* out)", () =>
                    $"{{\n    uint8_t* p = NULL;\n    int64_t n = 0;\n    uint32_t err = byn_io_read(path, &p, &n, byn_context);\n" +
                    $"    if (err == 0 && out) *out = ({list}){{p, n, n, byn_context}};\n    return err;\n}}\n");
                return $"{name}({Expr(c.Arguments[0])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.IoReadText:
                return $"byn_io_read_text({Expr(c.Arguments[0])}, {result ?? "NULL"}, byn_context)";
            case BuiltinFunction.IoWriteFile:
            {
                var span = _c.CType(fn.Parameters[1].Type);
                var name = _c.Helper("bynh_io_write_file", $"static uint32_t bynh_io_write_file(byn_str path, {span} bytes)", () =>
                    "{\n    return byn_io_write_file(path, bytes.ptr, bytes.len);\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])})";
            }
            case BuiltinFunction.IoListDir:
            {
                var list = _c.CType(fn.ReturnType);
                var name = _c.Helper("bynh_io_list_dir", $"static uint32_t bynh_io_list_dir(byn_str path, {list}* out)", () =>
                    $"{{\n    byn_str* p = NULL;\n    int64_t n = 0;\n    uint32_t err = byn_io_list_dir(path, &p, &n, byn_context);\n" +
                    $"    if (err == 0 && out) *out = ({list}){{p, n, n, byn_context}};\n    return err;\n}}\n");
                return $"{name}({Expr(c.Arguments[0])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.IoRun:
            {
                var span = _c.CType(fn.Parameters[1].Type);
                var name = _c.Helper("bynh_io_run", $"static uint32_t bynh_io_run(byn_str program, {span} args, byn_process* out)", () =>
                    "{\n    return byn_io_run(program, args.ptr, args.len, out, byn_context);\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.IoRunBatch:
            {
                var span = _c.CType(fn.Parameters[1].Type);
                var name = _c.Helper("bynh_io_run_batch", $"static uint32_t bynh_io_run_batch(byn_str path, {span} args, byn_process* out)", () =>
                    "{\n    return byn_io_run_batch(path, args.ptr, args.len, out, byn_context);\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.Utf8Decode:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var code = fn.ErrorSets[0].Variants[0].Code;
                var name = _c.Helper("bynh_utf8_decode", $"static {_c.ErrorCType} bynh_utf8_decode({span} bytes, byn_str* out)", () =>
                    $"{{\n    int64_t at = byn_utf8_invalid_at(bytes.ptr, bytes.len);\n" +
                    $"    if (at >= 0) return ({_c.ErrorCType}){{ .code = UINT32_C({code}), .p.e{code} = {{ at }} }};\n" +
                    $"    if (out) *out = byn_str_copy((byn_str){{bytes.ptr, bytes.len}}, byn_context);\n    return ({_c.ErrorCType}){{0}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.Utf8TryDecode:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var opt = _c.CType(fn.ReturnType);
                var name = _c.Helper("bynh_utf8_try_decode", $"static {opt} bynh_utf8_try_decode({span} bytes)", () =>
                    $"{{\n    if (byn_utf8_invalid_at(bytes.ptr, bytes.len) >= 0) return ({opt}){{0}};\n" +
                    $"    return ({opt}){{true, byn_str_copy((byn_str){{bytes.ptr, bytes.len}}, byn_context)}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.Utf8DecodeReplace:
            {
                // `invalid:` has one value, `.replace`, so the argument is not passed.
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_utf8_decode_replace", $"static byn_str bynh_utf8_decode_replace({span} bytes)", () =>
                    "{\n    return byn_utf8_decode_replace(bytes.ptr, bytes.len, byn_context);\n}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.HexDecode:
            {
                var list = _c.CType(fn.ReturnType);
                var code = fn.ErrorSets[0].Variants[0].Code;
                var name = _c.Helper("bynh_hex_decode", $"static {_c.ErrorCType} bynh_hex_decode(byn_str text, {list}* out)", () =>
                    $"{{\n    uint8_t* p = NULL;\n    int64_t at = byn_hex_decode(text, &p, byn_context);\n" +
                    $"    if (at >= 0) return ({_c.ErrorCType}){{ .code = UINT32_C({code}), .p.e{code} = {{ at }} }};\n" +
                    $"    if (out) *out = ({list}){{p, text.len / 2, text.len / 2, byn_context}};\n    return ({_c.ErrorCType}){{0}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.IntParse:
            {
                var t = (PrimitiveType)fn.ReturnType;
                var (bad, overflow) = (fn.ErrorSets[0].Variants[0].Code, fn.ErrorSets[0].Variants[1].Code);
                var name = "bynh_parse_" + _c.Key(t);
                _c.Helper(name, $"static {_c.ErrorCType} {name}(byn_str s, byn_builtin_Radix radix, {_c.CType(t)}* out)", () =>
                    $"{{\n    int64_t v = 0;\n    int64_t at = byn_int_parse_at(s, {t.Bits}, {(t.IsSignedInteger ? "true" : "false")}, radix, &v);\n" +
                    $"    if (at == -2) return ({_c.ErrorCType}){{ .code = UINT32_C({overflow}) }};\n" +
                    $"    if (at >= 0) return ({_c.ErrorCType}){{ .code = UINT32_C({bad}), .p.e{bad} = {{ at }} }};\n" +
                    $"    if (out) *out = ({_c.CType(t)})v;\n    return ({_c.ErrorCType}){{0}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])}, {result ?? "NULL"})";
            }
            case BuiltinFunction.SymbolIntern:
                return _c.SymbolIntern(Expr(c.Arguments[0]));
            case BuiltinFunction.PathIsRooted:
                return $"byn_path_is_rooted({Expr(c.Arguments[0])})";
            case BuiltinFunction.PathRelative:
                return $"byn_path_relative({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])}, byn_context, {Loc(c.Syntax)})";
            case BuiltinFunction.PathFileName:
                return $"byn_path_file_name({Expr(c.Arguments[0])}, byn_context)";
            case BuiltinFunction.PathDirectoryName:
            {
                var opt = _c.CType(fn.ReturnType);
                var name = _c.Helper("bynh_path_directory_name", $"static {opt} bynh_path_directory_name(byn_str path)", () =>
                    $"{{\n    {opt} r = {{0}};\n    r.has = byn_path_directory_name(path, &r.value, byn_context);\n    return r;\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.PathCombine:
                return $"byn_path_combine({Expr(c.Arguments[0])}, {Expr(c.Arguments[1])}, byn_context)";
            case BuiltinFunction.PathCombineSpan:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_path_combine_span", $"static byn_str bynh_path_combine_span({span} paths)", () =>
                    "{\n    return byn_path_combine_span(paths.ptr, paths.len, byn_context);\n}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.PathFullPath:
                return $"byn_path_full_path({Expr(c.Arguments[0])}, byn_context, {Loc(c.Syntax)})";
            case BuiltinFunction.HexEncode:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_hex_encode", $"static byn_str bynh_hex_encode({span} bytes)", () =>
                    "{\n    return byn_hex_encode(bytes.ptr, bytes.len, byn_context);\n}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.StringInvalidUtf8At:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var opt = _c.CType(fn.ReturnType);
                var name = _c.Helper("bynh_string_invalid_utf8_at", $"static {opt} bynh_string_invalid_utf8_at({span} bytes)", () =>
                    $"{{\n    int64_t i = byn_utf8_invalid_at(bytes.ptr, bytes.len);\n    return i < 0 ? ({opt}){{0}} : ({opt}){{true, i}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.IoMonotonicNanos:
                return "byn_io_monotonic_nanos()";
            case BuiltinFunction.IoStdout:
                return "INT32_C(1)";
            case BuiltinFunction.IoStderr:
                return "INT32_C(2)";
            case BuiltinFunction.IoStdin:
                return "INT32_C(0)";
            case BuiltinFunction.EnumFromOrdinal:
            {
                var e = (EnumSymbol)((OptionalType)fn.ReturnType).Inner;
                var opt = _c.CType(fn.ReturnType);
                var name = "bynh_from_ordinal_" + _c.Key(e);
                _c.Helper(name, $"static {opt} {name}(int64_t i)", () =>
                    $"{{\n    if (i < 0 || i >= {e.Members.Count}) return ({opt}){{0}};\n    return ({opt}){{true, ({_c.CType(e)})i}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
            case BuiltinFunction.EnumParse:
            {
                var e = (EnumSymbol)((OptionalType)fn.ReturnType).Inner;
                var opt = _c.CType(fn.ReturnType);
                var name = "bynh_parse_" + _c.Key(e);
                var names = _c.EnumNames(e);
                _c.Helper(name, $"static {opt} {name}(byn_str s)", () =>
                    $"{{\n    for (int32_t i = 0; i < {e.Members.Count}; i++)\n        if (byn_str_eq(s, {names}[i])) return ({opt}){{true, ({_c.CType(e)})i}};\n    return ({opt}){{0}};\n}}\n");
                return $"{name}({Expr(c.Arguments[0])})";
            }
        }
        // Through `dyn ref` the conformer's method is the vtable slot; the receiver is a local, so naming it twice is safe.
        var dyn = c.Receiver is { Type: DynRefType } ? Expr(c.Receiver) : null;
        // Through a function value: its code with its environment first; lowering leaves the receiver a local, so naming it twice is safe.
        var value = fn.Kind == FunctionKind.Invoke ? Expr(c.Receiver!) : null;
        if (dyn is not null)
        {
            args.Add(dyn + ".data");
        }
        else if (value is not null)
        {
            args.Add(value + ".env");
        }
        else if (fn.HasThis && fn.Kind != FunctionKind.Constructor)
        {
            args.Add("&" + Expr(c.Receiver!));
            ClaimAfterCall(c.Receiver!, c.Syntax);
        }
        for (var i = 0; i < c.Arguments.Length; i++)
        {
            if (fn.Parameters[i].IsByRef) ClaimAfterCall(c.Arguments[i], c.Syntax);
            // An `out` argument initializes a moved-from local again.
            if (fn.Parameters[i].Modifier == ParamModifier.Out && c.Arguments[i] is BoundLocal { Local: var o } && HasSlot(o))
                args.Add($"({Slot(o)}.line = 0, &{_names[o]})");
            else
                args.Add(fn.Parameters[i].IsByRef ? "&" + Expr(c.Arguments[i]) : Expr(c.Arguments[i]));
        }
        if (result is not null) args.Add(result);
        return $"{(dyn is not null ? $"{dyn}.vt->{CEmitter.SlotName(fn)}" : value is not null ? value + ".fn" : _c.FunctionName(fn))}({string.Join(", ", args)})";
    }

    private string Builtin(BoundBuiltinCall b)
    {
        var r = b.Receiver;
        var arg = b.Arguments.Length > 0 ? Expr(b.Arguments[0]) : "";
        switch (b.Member)
        {
            case BuiltinMember.StringLength or BuiltinMember.SpanLength or BuiltinMember.ListLength or BuiltinMember.StrBufLength:
                return $"{Expr(r)}.len";
            case BuiltinMember.StringIsEmpty or BuiltinMember.SpanIsEmpty or BuiltinMember.ListIsEmpty:
                return $"({Expr(r)}.len == 0)";
            case BuiltinMember.StringRuneCount:
                return $"byn_str_rune_count({Expr(r)})";
            case BuiltinMember.StringIsAscii:
                return $"byn_str_is_ascii({Expr(r)})";
            case BuiltinMember.StringBytes:
            {
                var span = _c.CType(b.Type);
                var name = _c.Helper("bynh_str_bytes", $"static {span} bynh_str_bytes(byn_str s)", () => $"{{\n    return ({span}){{(uint8_t*)s.ptr, s.len}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.StringCopy:
                return $"byn_str_copy({Expr(r)}, {(b.Arguments.Length > 0 ? $"byn_arena_alloc({arg})" : "byn_context")})";
            case BuiltinMember.StringStartsWith:
                return $"byn_str_starts_with({Expr(r)}, {arg})";
            case BuiltinMember.StringEndsWith:
                return $"byn_str_ends_with({Expr(r)}, {arg})";
            case BuiltinMember.StringContains:
                return $"byn_str_contains({Expr(r)}, {arg})";
            case BuiltinMember.StringPosition or BuiltinMember.StringLastPosition:
            {
                var opt = _c.CType(b.Type);
                var name = _c.Helper("bynh_position", $"static {opt} bynh_position(int64_t p)", () => $"{{\n    return p < 0 ? ({opt}){{0}} : ({opt}){{true, p}};\n}}\n");
                return b.Member == BuiltinMember.StringLastPosition ? $"{name}(byn_str_last_position({Expr(r)}, {arg}))"
                    : $"{name}(byn_str_position({Expr(r)}, {arg}, {(b.Arguments.Length > 1 ? Expr(b.Arguments[1]) : "0")}, {Loc(b.Syntax)}))";
            }
            case BuiltinMember.StringCount:
                return $"byn_str_count({Expr(r)}, {arg})";
            case BuiltinMember.StringTrimmed:
                return $"byn_str_trimmed({Expr(r)}, {(b.Arguments.Length > 0 ? arg : "2")})";
            case BuiltinMember.StringTrimmedBy:
            {
                var st = _c.CType(b.Arguments[0].Type);
                var name = _c.Helper("bynh_trimmed_by", $"static byn_str bynh_trimmed_by(byn_str s, {st} by)", () => "{\n    return byn_str_trimmed_by(s, by.ptr, by.len);\n}\n");
                return $"{name}({Expr(r)}, {arg})";
            }
            case BuiltinMember.StringLowercased or BuiltinMember.StringUppercased:
                return $"byn_str_case({Expr(r)}, {(b.Member == BuiltinMember.StringUppercased ? "true" : "false")}, byn_context)";
            case BuiltinMember.StringEquals:
                return b.Arguments.Length > 1 ? $"({Expr(b.Arguments[1])} == 1 ? byn_str_eq_caseless({Expr(r)}, {arg}) : byn_str_eq({Expr(r)}, {arg}))"
                    : $"byn_str_eq({Expr(r)}, {arg})";
            case BuiltinMember.StringReplaced:
                return $"byn_str_replaced({Expr(r)}, {arg}, {Expr(b.Arguments[1])}, byn_context, {Loc(b.Syntax)})";
            case BuiltinMember.StringRepeated:
                return $"byn_str_repeated({Expr(r)}, {arg}, byn_context, {Loc(b.Syntax)})";
            case BuiltinMember.StringPadded:
                return $"byn_str_padded({Expr(r)}, {arg}, {Expr(b.Arguments[1])}, byn_context, {Loc(b.Syntax)})";
            case BuiltinMember.BytesToString:
            {
                var st = _c.CType(r.Type);
                var name = "bynh_bytes_string_" + _c.Key(r.Type);
                _c.Helper(name, $"static byn_str {name}({st} b)", () => "{\n    return byn_bytes_string(b.ptr, b.len, byn_context);\n}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.IntTryParse:
            {
                var opt = _c.CType(b.Type);
                var t = (PrimitiveType)((OptionalType)b.Type).Inner;
                var name = "bynh_try_parse_" + _c.Key(b.Type);
                _c.Helper(name, $"static {opt} {name}(byn_str s, byn_builtin_Radix radix)", () =>
                    $"{{\n    int64_t v;\n    if (!byn_int_parse(s, {t.Bits}, {(t.IsSignedInteger ? "true" : "false")}, radix, &v)) return ({opt}){{0}};\n    return ({opt}){{true, ({_c.CType(t)})v}};\n}}\n");
                return $"{name}({Expr(r)}, {arg})";
            }
            case BuiltinMember.FloatTryParse:
            {
                var opt = _c.CType(b.Type);
                var t = (PrimitiveType)((OptionalType)b.Type).Inner;
                var name = "bynh_try_parse_" + _c.Key(b.Type);
                _c.Helper(name, $"static {opt} {name}(byn_str s)", () =>
                    $"{{\n    double v;\n    if (!byn_float_parse(s, {(t == PrimitiveType.F32 ? "true" : "false")}, &v)) return ({opt}){{0}};\n    return ({opt}){{true, ({_c.CType(t)})v}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.StringJoined:
            {
                var xt = _c.CType(r.Type);
                var name = "bynh_joined_" + _c.Key(r.Type);
                _c.Helper(name, $"static byn_str {name}({xt} xs, byn_str sep)", () => "{\n    return byn_str_joined(xs.ptr, xs.len, sep, byn_context);\n}\n");
                return $"{name}({Expr(r)}, {arg})";
            }
            case BuiltinMember.StringRunes or BuiltinMember.StringUtf16 or BuiltinMember.StringLines:
                return $"((byn_text_view){{{Expr(r)}, {{NULL, 0}}, 0, 0}})";
            case BuiltinMember.StringParts:
                return $"byn_parts({Expr(r)}, {arg}, {(b.Arguments.Length > 1 ? Expr(b.Arguments[1]) : "0")}, {Loc(b.Syntax)})";
            case BuiltinMember.StringPartsRune:
                return $"byn_parts_rune({Expr(r)}, {arg}, {(b.Arguments.Length > 1 ? Expr(b.Arguments[1]) : "0")}, {Loc(b.Syntax)})";
            case BuiltinMember.RunesTake:
                return $"byn_str_take_runes({Expr(r)}.s, {arg}, {Loc(b.Syntax)})";
            case BuiltinMember.RunesSkip:
                return $"byn_str_skip_runes({Expr(r)}.s, {arg}, {Loc(b.Syntax)})";
            case BuiltinMember.RunesTakeLast:
                return $"byn_str_take_last_runes({Expr(r)}.s, {arg}, {Loc(b.Syntax)})";
            case BuiltinMember.Utf16Copy:
            {
                var list = _c.CType(b.Type);
                var name = _c.Helper("bynh_utf16_copy", $"static {list} bynh_utf16_copy(byn_text_view v)", () =>
                    $"{{\n    {list} r = {{NULL, 0, 0, byn_context}};\n    r.ptr = byn_utf16_copy(v.s, &r.len, byn_context);\n    r.cap = r.len;\n    return r;\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.TextViewMore:
                return $"byn_view_more({Expr(r)}, {arg}, {(int)((TextViewType)r.Type).Kind})";
            case BuiltinMember.TextViewNext:
                return ((TextViewType)r.Type).Kind switch
                {
                    TextViewKind.Runes => $"byn_str_next({Expr(r)}.s, &{arg})",
                    TextViewKind.Utf16 => $"byn_utf16_next(&{Expr(r)}, &{arg})",
                    TextViewKind.Lines => $"byn_lines_next(&{Expr(r)}, &{arg})",
                    _ => $"byn_parts_next(&{Expr(r)}, &{arg})",
                };
            case BuiltinMember.SpanCopy:
            {
                var span = (SpanType)r.Type;
                var list = _c.CType(b.Type);
                var st = _c.CType(span);
                var et = _c.CType(span.Element);
                var name = "bynh_copy_" + _c.Key(span);
                _c.Helper(name, $"static {list} {name}({st} s, byn_alloc* a)", () =>
                    $"{{\n    {list} r = {{NULL, 0, 0, a}};\n    if (s.len > 0) {{\n        r.ptr = ({et}*)byn_copy_bytes(s.ptr, s.len * (int64_t)sizeof({et}), a);\n        r.len = r.cap = s.len;\n    }}\n    return r;\n}}\n");
                return $"{name}({Expr(r)}, {(b.Arguments.Length > 0 ? $"byn_arena_alloc({arg})" : "byn_context")})";
            }
            case BuiltinMember.ListCopy:
            {
                var lt = _c.CType(r.Type);
                var et = _c.CType(((ListType)r.Type).Element);
                var name = "bynh_copy_" + _c.Key(r.Type);
                _c.Helper(name, $"static {lt} {name}({lt} l, byn_alloc* a)", () =>
                    $"{{\n    {lt} r = {{NULL, 0, 0, a}};\n    if (l.len > 0) {{\n        r.ptr = ({et}*)byn_copy_bytes(l.ptr, l.len * (int64_t)sizeof({et}), a);\n        r.len = r.cap = l.len;\n    }}\n    return r;\n}}\n");
                return $"{name}({Expr(r)}, {(b.Arguments.Length > 0 ? $"byn_arena_alloc({arg})" : "byn_context")})";
            }
            case BuiltinMember.StrBufCopy:
                return $"byn_strbuf_copy({Expr(r)}, byn_arena_alloc({arg}))";
            case BuiltinMember.ListAdd:
            {
                var lt = _c.CType(r.Type);
                var et = _c.CType(((ListType)r.Type).Element);
                var name = "bynh_add_" + _c.Key(r.Type);
                _c.Helper(name, $"static void {name}({lt}* l, {et} v)", () =>
                    $"{{\n    if (!l->alloc) l->alloc = byn_context;\n    byn_list_reserve((void**)&l->ptr, &l->cap, l->len + 1, (int64_t)sizeof({et}), l->alloc);\n    l->ptr[l->len++] = v;\n}}\n");
                return Claimed($"{name}(&{Expr(r)}, {arg})", r, b.Syntax);
            }
            case BuiltinMember.ListAsSpan:
            {
                var lt = _c.CType(r.Type);
                var st = _c.CType(b.Type);
                var name = "bynh_span_" + _c.Key(r.Type);
                _c.Helper(name, $"static {st} {name}({lt} l)", () => $"{{\n    return ({st}){{l.ptr, l.len}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.ListMutableSpan:
            {
                var lt = _c.CType(r.Type);
                var st = _c.CType(b.Type);
                var name = "bynh_mutable_span_" + _c.Key(r.Type);
                _c.Helper(name, $"static {st} {name}({lt} l)", () => $"{{\n    return ({st}){{l.ptr, l.len}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.ListClear or BuiltinMember.StrBufClear:
                return $"({Expr(r)}.len = 0)";
            case BuiltinMember.ListRemoveLast:
            {
                var lt = _c.CType(r.Type);
                var et = _c.CType(b.Type);
                var name = "bynh_pop_" + _c.Key(r.Type);
                _c.Helper(name, $"static {et} {name}({lt}* l, const char* file, int line)", () =>
                    $"{{\n    if (l->len == 0) byn_panic(\"removeLast on an empty list\", file, line);\n    return l->ptr[--l->len];\n}}\n");
                return $"{name}(&{Expr(r)}, {Loc(b.Syntax)})";
            }
            case BuiltinMember.ListTryGet:
            {
                var lt = _c.CType(r.Type);
                var opt = _c.CType(b.Type);
                var name = "bynh_try_get_" + _c.Key(r.Type);
                _c.Helper(name, $"static {opt} {name}({lt} l, int64_t i)", () =>
                    $"{{\n    return i < 0 || i >= l.len ? ({opt}){{0}} : ({opt}){{true, l.ptr[i]}};\n}}\n");
                return $"{name}({Expr(r)}, {arg})";
            }
            case BuiltinMember.ListRemoveRange:
            {
                var lt = _c.CType(r.Type);
                var name = "bynh_remove_range_" + _c.Key(r.Type);
                _c.Helper(name, $"static void {name}({lt}* l, int64_t start, int64_t end, const char* file, int line)", () =>
                    "{\n    byn_slice_check(start, end, l->len, file, line);\n    if (end > start) memmove(l->ptr + start, l->ptr + end, (size_t)(l->len - end) * sizeof(*l->ptr));\n    l->len -= end - start;\n}\n");
                return $"{name}(&{Expr(r)}, {arg}, {Expr(b.Arguments[1])}, {Loc(b.Syntax)})";
            }
            case BuiltinMember.ListRemoveThrough or BuiltinMember.ListRemoveAt or BuiltinMember.ListRemoveAtRange:
            {
                // `through:` is an inclusive end and `at: i` removes one element (mode 1 and 2; mode 0 is `until`).
                var lt = _c.CType(r.Type);
                var name = "bynh_remove_through_" + _c.Key(r.Type);
                _c.Helper(name, $"static void {name}({lt}* l, int64_t start, int64_t end, int mode, const char* file, int line)", () =>
                    "{\n    if (mode == 2) {\n        if (start < 0 || start >= l->len) bayan_trap_bounds(file, line);\n        end = start;\n    }\n    if (mode != 0) {\n        byn_slice_check(start, end, l->len - 1, file, line);\n        end++;\n    }\n"
                    + "    byn_slice_check(start, end, l->len, file, line);\n    if (end > start) memmove(l->ptr + start, l->ptr + end, (size_t)(l->len - end) * sizeof(*l->ptr));\n    l->len -= end - start;\n}\n");
                if (b.Member == BuiltinMember.ListRemoveThrough) return $"{name}(&{Expr(r)}, {arg}, {Expr(b.Arguments[1])}, 1, {Loc(b.Syntax)})";
                if (b.Member == BuiltinMember.ListRemoveAt) return $"{name}(&{Expr(r)}, {arg}, 0, 2, {Loc(b.Syntax)})";
                // `at: a..b` or `at: a..=b` reads the range's layout tuple (start, end, inclusive).
                var range = "bynh_remove_at_range_" + _c.Key(r.Type);
                _c.Helper(range, $"static void {range}({lt}* l, {_c.CType(b.Arguments[0].Type)} at, const char* file, int line)", () =>
                    $"{{\n    {name}(l, at.item1, at.item2, at.item3 ? 1 : 0, file, line);\n}}\n");
                return $"{range}(&{Expr(r)}, {arg}, {Loc(b.Syntax)})";
            }
            case BuiltinMember.ListReplace:
            {
                var lt = _c.CType(r.Type);
                var name = "bynh_replace_" + _c.Key(r.Type);
                _c.Helper(name, $"static void {name}({lt}* l, {_c.CType(b.Arguments[0].Type)} at, {_c.CType(b.Arguments[1].Type)} items, const char* file, int line)", () =>
                    "{\n    int64_t start = at.item1, end = at.item3 ? at.item2 + 1 : at.item2;\n    byn_slice_check(start, end, l->len, file, line);\n"
                    + "    int64_t len = l->len - (end - start) + items.len;\n    if (!l->alloc) l->alloc = byn_context;\n"
                    // Items read from the list itself are copied first, since growing and shifting move them.
                    + "    void* copy = NULL;\n    if (items.len > 0 && items.ptr >= l->ptr && items.ptr < l->ptr + l->cap)\n"
                    + "        items.ptr = copy = byn_copy_bytes(items.ptr, items.len * (int64_t)sizeof(*l->ptr), l->alloc);\n"
                    + "    byn_list_reserve((void**)&l->ptr, &l->cap, len, (int64_t)sizeof(*l->ptr), l->alloc);\n"
                    + "    memmove(l->ptr + start + items.len, l->ptr + end, (size_t)(l->len - end) * sizeof(*l->ptr));\n"
                    + "    if (items.len > 0) memcpy(l->ptr + start, items.ptr, (size_t)items.len * sizeof(*l->ptr));\n    l->len = len;\n"
                    + "    if (copy) byn_release(l->alloc, copy);\n}\n");
                return $"{name}(&{Expr(r)}, {arg}, {Expr(b.Arguments[1])}, {Loc(b.Syntax)})";
            }
            case BuiltinMember.ListSort:
            {
                var element = ((ListType)r.Type).Element;
                var et = _c.CType(element);
                var less = _c.Helper("bynh_less_" + _c.Key(element), $"static bool bynh_less_{_c.Key(element)}(const void* a, const void* b)", () => element.IsString
                    ? "{\n    return byn_str_cmp(*(const byn_str*)a, *(const byn_str*)b) < 0;\n}\n"
                    : $"{{\n    return *(const {et}*)a < *(const {et}*)b;\n}}\n");
                // The list is read once, through a pointer, so a receiver with side effects runs once.
                var lt = _c.CType(r.Type);
                var name = _c.Helper("bynh_sort_" + _c.Key(r.Type), $"static void bynh_sort_{_c.Key(r.Type)}({lt}* l)", () =>
                    $"{{\n    byn_sort(l->ptr, l->len, sizeof(*l->ptr), {less});\n}}\n");
                return $"{name}(&{Expr(r)})";
            }
            case BuiltinMember.MapLength:
                return $"{Expr(r)}.h.live";
            case BuiltinMember.SymbolText:
                return _c.SymbolText(Expr(r));
            case BuiltinMember.MapClear:
                return $"byn_map_clear(&{Expr(r)}.h)";
            case BuiltinMember.MapSlotCount:
                return $"{Expr(r)}.h.len";
            case BuiltinMember.MapSlotLive:
                return $"(!{Expr(r)}.h.dead[{arg}])";
            case BuiltinMember.MapSlotEntry:
            {
                var m = Expr(r);
                return $"(({_c.CType(b.Type)}){{{m}.keys[{arg}], {m}.vals[{arg}]}})";
            }
            case BuiltinMember.MapCopy:
            {
                var mt = _c.CType(r.Type);
                var map = (MapType)r.Type;
                var kt = _c.CType(map.KeyType);
                var vt = _c.CType(map.ValueType);
                var name = "bynh_copy_" + _c.Key(r.Type);
                _c.Helper(name, $"static {mt} {name}({mt} m, byn_alloc* a)", () =>
                    $"{{\n    {mt} r;\n    byn_map_copy(&m.h, m.keys, (int64_t)sizeof({kt}), (void**)&r.keys, m.vals, (int64_t)sizeof({vt}), (void**)&r.vals, &r.h, a);\n    return r;\n}}\n");
                return $"{name}({Expr(r)}, byn_arena_alloc({arg}))";
            }
            case BuiltinMember.MapIndex or BuiltinMember.MapIndexSet or BuiltinMember.MapSlot or BuiltinMember.MapTryGet
                or BuiltinMember.MapContains or BuiltinMember.MapRemove:
                return _c.MapMethod(b.Member, (MapType)r.Type, Expr(r), b.Arguments.Select(Expr).ToArray(), Loc(b.Syntax));
            case BuiltinMember.ArrayLength:
                return $"((void){Expr(r)}, INT64_C({((ArrayType)r.Type).Length}))";
            case BuiltinMember.ArrayAsSpan or BuiltinMember.ArrayMutableSpan:
                return $"(({_c.CType(b.Type)}){{{Expr(r)}.v, {((ArrayType)r.Type).Length}}})";
            case BuiltinMember.ArenaReset:
                return $"byn_arena_reset({Expr(r)})";
            case BuiltinMember.StrBufAppend:
                return Claimed($"byn_w_str(&{Expr(r)}, {arg})", r, b.Syntax);
            case BuiltinMember.StrBufAppendRepeated:
            {
                var name = _c.Helper("bynh_strbuf_repeat", "static void bynh_strbuf_repeat(byn_writer* w, uint32_t c, int64_t n, const char* file, int line)", () =>
                    "{\n    if (n < 0) byn_panic(\"repeated a negative number of times\", file, line);\n"
                    + "    for (int64_t i = 0; i < n; i++) byn_w_char(w, c);\n}\n");
                return Claimed($"{name}(&{Expr(r)}, {arg}, {Expr(b.Arguments[1])}, {Loc(b.Syntax)})", r, b.Syntax);
            }
            case BuiltinMember.StrBufInsert:
            {
                // Appends the text, then rotates it into place by three reversals; text the buffer grew away from stays valid.
                _c.Helper("bynh_reverse", "static void bynh_reverse(uint8_t* p, int64_t n)", () =>
                    "{\n    for (int64_t i = 0, j = n - 1; i < j; i++, j--) {\n        uint8_t t = p[i];\n        p[i] = p[j];\n        p[j] = t;\n    }\n}\n");
                var name = _c.Helper("bynh_strbuf_insert", "static void bynh_strbuf_insert(byn_writer* w, byn_str s, int64_t at, const char* file, int line)", () =>
                    "{\n    byn_slice_check(at, w->len, w->len, file, line);\n"
                    + "    if (at < w->len && (w->buf[at] & 0xC0) == 0x80) byn_panic(\"string slice splits a code point\", file, line);\n"
                    + "    int64_t end = w->len;\n    byn_w_bytes(w, s.ptr, s.len);\n"
                    + "    bynh_reverse(w->buf + at, end - at);\n    bynh_reverse(w->buf + end, s.len);\n    bynh_reverse(w->buf + at, end - at + s.len);\n}\n");
                return Claimed($"{name}(&{Expr(r)}, {arg}, {Expr(b.Arguments[1])}, {Loc(b.Syntax)})", r, b.Syntax);
            }
            case BuiltinMember.IoWrite:
                return $"byn_io_write({Expr(r)}, {arg})";
            case BuiltinMember.IoReadAll:
            {
                var res = _c.CType(b.Type);
                var name = _c.Helper("bynh_io_read_all", $"static {res} bynh_io_read_all(int32_t fd)", () =>
                    $"{{\n    (void)fd;\n    {res} r = {{0}};\n    r.err.code = byn_io_read_stdin(&r.value, byn_context);\n    return r;\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.StrBufAsString:
                return $"byn_strbuf_str({Expr(r)})";
            case BuiltinMember.PanicMessage:
                return $"{Expr(r)}.message";
            case BuiltinMember.ProcessExitCode:
                return $"{Expr(r)}.exit_code";
            case BuiltinMember.FormatSpecRadix or BuiltinMember.FormatSpecDebug or BuiltinMember.FormatSpecWidth
                or BuiltinMember.FormatSpecFill or BuiltinMember.FormatSpecAlign or BuiltinMember.FormatSpecDigits:
                return $"{Expr(r)}.{b.Member.ToString()[10..].ToLowerInvariant()}";
            case BuiltinMember.ProcessStdout:
                return $"{Expr(r)}.out";
            case BuiltinMember.ProcessStderr:
                return $"{Expr(r)}.err";
            case BuiltinMember.CharValue:
                return $"((uint32_t){Expr(r)})";
            case BuiltinMember.IntToString:
            {
                var t = (PrimitiveType)r.Type;
                return $"byn_int_string((int64_t){Expr(r)}, {t.Bits}, {(t.IsSignedInteger ? "true" : "false")}, {arg}, byn_context)";
            }
            case BuiltinMember.EnumName:
                return $"{_c.EnumNames((EnumSymbol)r.Type)}[{Expr(r)}]";
            case BuiltinMember.EnumOrdinal:
                return $"((int32_t){Expr(r)})";
            case BuiltinMember.EnumField:
            {
                var e = (EnumSymbol)r.Type;
                return $"{_c.EnumField(e.Fields[(int)(Int128)((BoundLiteral)b.Arguments[0]).Value.Value])}[{Expr(r)}]";
            }
            case BuiltinMember.ResultIsOk:
                return $"({Expr(r)}.err.code == 0)";
            case BuiltinMember.OwnedValue:
                return $"(*{Expr(r)})";
            case BuiltinMember.ResultValue or BuiltinMember.ResultError:
            {
                var value = b.Member == BuiltinMember.ResultValue;
                var res = _c.CType(r.Type);
                var name = (value ? "bynh_value_" : "bynh_error_") + _c.Key(r.Type);
                var message = value ? "result holds an error" : "result holds a value";
                _c.Helper(name, $"static {_c.CType(b.Type)} {name}({res} r, const char* file, int line)", () =>
                    $"{{\n    if ({(value ? "r.err.code" : "!r.err.code")}) byn_panic(\"{message}\", file, line);\n    return {(value ? "r.value" : "r.err")};\n}}\n");
                return $"{name}({Expr(r)}, {Loc(b.Syntax)})";
            }
            default:
                throw new InvalidOperationException($"cannot emit {b.Member}");
        }
    }

    private string Unary(BoundUnary u)
    {
        var v = Expr(u.Operand);
        return u.Op switch
        {
            UnaryOp.Plus => v,
            UnaryOp.Negate when u.Type.IsInteger => $"byn_neg_{CEmitter.IntSuffix(u.Type)}({v}, {Loc(u.Syntax)})",
            UnaryOp.Negate => $"(-{v})",
            UnaryOp.Not => $"(!{v})",
            UnaryOp.Complement => $"(({_c.CType(u.Type)})~{v})",
            _ => throw new InvalidOperationException($"cannot emit unary {u.Op}"),
        };
    }

    private static bool BareCase(BoundExpr e) => e switch
    {
        BoundErrorVariant { Payload.Length: 0, Variant.Fields.Count: > 0 } => true,
        BoundConversion c => BareCase(c.Operand),
        _ => false,
    };

    private string Binary(BoundBinary b)
    {
        var l = Expr(b.Left);
        var r = Expr(b.Right);
        var t = b.Left.Type;
        if (t.IsInteger)
        {
            var n = CEmitter.IntSuffix(t);
            switch (b.Op)
            {
                case BinaryOp.Add: return $"byn_add_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Sub: return $"byn_sub_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Mul: return $"byn_mul_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Div: return $"byn_div_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Rem: return $"byn_rem_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.AddWrap: return $"byn_addw_{n}({l}, {r})";
                case BinaryOp.SubWrap: return $"byn_subw_{n}({l}, {r})";
                case BinaryOp.MulWrap: return $"byn_mulw_{n}({l}, {r})";
                case BinaryOp.AddSat: return $"byn_adds_{n}({l}, {r})";
                case BinaryOp.SubSat: return $"byn_subs_{n}({l}, {r})";
                case BinaryOp.MulSat: return $"byn_muls_{n}({l}, {r})";
                case BinaryOp.Shl: return $"byn_shl_{n}({l}, (int64_t)({r}))";
                case BinaryOp.Shr: return $"byn_shr_{n}({l}, (int64_t)({r}))";
                case BinaryOp.BitAnd: return $"(({_c.CType(t)})({l} & {r}))";
                case BinaryOp.BitOr: return $"(({_c.CType(t)})({l} | {r}))";
                case BinaryOp.BitXor: return $"(({_c.CType(t)})({l} ^ {r}))";
            }
        }
        if (t.IsFloat && b.Op == BinaryOp.Rem) return t == PrimitiveType.F32 ? $"fmodf({l}, {r})" : $"fmod({l}, {r})";
        if (t.IsString && b.Op is BinaryOp.Lt or BinaryOp.Gt or BinaryOp.Le or BinaryOp.Ge)
            return $"(byn_str_cmp({l}, {r}) {Op(b.Op)} 0)";
        // Symbols order by text, as `string` does (R1).
        if (t == BuiltinType.Symbol && b.Op is BinaryOp.Lt or BinaryOp.Gt or BinaryOp.Le or BinaryOp.Ge)
            return $"(byn_str_cmp({_c.SymbolText(l)}, {_c.SymbolText(r)}) {Op(b.Op)} 0)";
        // `== .case` with a payload case written bare tests the code (Q312).
        if (b.Op is BinaryOp.Eq or BinaryOp.Ne && (BareCase(b.Left) || BareCase(b.Right)))
            return $"({l}.code {(b.Op == BinaryOp.Eq ? "==" : "!=")} {r}.code)";
        return b.Op switch
        {
            BinaryOp.Eq => _c.Equal(t, l, r),
            BinaryOp.Ne => $"(!{_c.Equal(t, l, r)})",
            _ => $"({l} {Op(b.Op)} {r})",
        };
    }

    private static string Op(BinaryOp op) => op switch
    {
        BinaryOp.Add => "+", BinaryOp.Sub => "-", BinaryOp.Mul => "*", BinaryOp.Div => "/",
        BinaryOp.Lt => "<", BinaryOp.Gt => ">", BinaryOp.Le => "<=", BinaryOp.Ge => ">=",
        BinaryOp.BitAnd => "&", BinaryOp.BitOr => "|", BinaryOp.BitXor => "^",
        BinaryOp.LogicalAnd => "&&", BinaryOp.LogicalOr => "||",
        _ => throw new InvalidOperationException($"no C operator for {op}"),
    };

    private string Conversion(BoundConversion c)
    {
        var v = Expr(c.Operand);
        var from = c.Operand.Type;
        var to = c.Type;
        switch (c.Kind)
        {
            case ConversionKind.Identity or ConversionKind.FromNever:
                return v;
            case ConversionKind.Widen:
                return $"(({_c.CType(to)}){v})";
            case ConversionKind.NumericCast when to.IsInteger && from.IsFloat:
                return $"byn_f2i_{CEmitter.IntSuffix(to)}((double){v})";
            case ConversionKind.NumericCast or ConversionKind.CharToInteger when to.IsInteger:
                return from.IsSignedInteger
                    ? $"byn_cast_{CEmitter.IntSuffix(to)}_i((int64_t){v}, {Loc(c.Syntax)})"
                    : $"byn_cast_{CEmitter.IntSuffix(to)}_u((uint64_t){v}, {Loc(c.Syntax)})";
            case ConversionKind.NumericCast:
                return $"(({_c.CType(to)}){v})";
            case ConversionKind.IntegerToChar:
                return from.IsSignedInteger
                    ? $"byn_to_char((int64_t){v}, {Loc(c.Syntax)})"
                    : $"byn_to_char_u((uint64_t){v}, {Loc(c.Syntax)})";
            case ConversionKind.ToOptional:
                return $"(({_c.CType(to)}){{true, {v}}})";
            case ConversionKind.NullToOptional:
                return $"(({_c.CType(to)}){{0}})";
            case ConversionKind.ToResult:
                return $"(({_c.CType(to)}){{{{0}}, {v}}})";
            case ConversionKind.ErrorToResult:
                return $"(({_c.CType(to)}){{{v}}})";
            case ConversionKind.ListToSpan:
                return $"(({_c.CType(to)}){{{v}.ptr, {v}.len}})";
            case ConversionKind.StringToBytes:
                return $"(({_c.CType(to)}){{(uint8_t*){v}.ptr, {v}.len}})";
            case ConversionKind.ArrayToSpan:
                return $"(({_c.CType(to)}){{{v}.v, {((ArrayType)from).Length}}})";
            case ConversionKind.ToDynRef:
                return $"(({_c.CType(to)}){{&{v}, &{_c.Vtable((StructSymbol)from, ((DynRefType)to).Interface)}}})";
            default:
                throw new InvalidOperationException($"cannot emit conversion {c.Kind}");
        }
    }

    private string Index(BoundIndex i)
    {
        var target = i.Target.Type;
        var et = _c.CType(i.Type);
        var tt = _c.CType(target);
        var name = "bynh_at_" + _c.Key(target);
        if (target is ArrayType a)
        {
            _c.Helper(name, $"static {et}* {name}({tt}* a, int64_t i, bool from_end, const char* file, int line)", () =>
                $"{{\n    if (from_end) i = {a.Length} - i;\n    return &a->v[byn_index(i, {a.Length}, file, line)];\n}}\n");
            return $"(*{name}(&{Expr(i.Target)}, (int64_t){Expr(i.Index)}, {(i.FromEnd ? "true" : "false")}, {Loc(i.Syntax)}))";
        }
        _c.Helper(name, $"static {et}* {name}({tt} s, int64_t i, bool from_end, const char* file, int line)", () =>
            "{\n    if (from_end) i = s.len - i;\n    return &s.ptr[byn_index(i, s.len, file, line)];\n}\n");
        return $"(*{name}({Expr(i.Target)}, (int64_t){Expr(i.Index)}, {(i.FromEnd ? "true" : "false")}, {Loc(i.Syntax)}))";
    }

    private string Slice(BoundSlice s)
    {
        var start = s.Start is null ? "0, 2" : $"(int64_t){Expr(s.Start)}, {(s.StartFromEnd ? 1 : 0)}";
        var end = s.End is null ? "0, 2" : $"(int64_t){Expr(s.End)}, {(s.EndFromEnd ? 1 : 0)}";
        var tail = $"{start}, {end}, {(s.Inclusive ? "true" : "false")}, {Loc(s.Syntax)}";
        var target = s.Target.Type;
        if (target.IsString)
        {
            var str = _c.Helper("bynh_slice_str",
                "static byn_str bynh_slice_str(byn_str s, int64_t a, int am, int64_t b, int bm, bool incl, const char* file, int line)",
                () => "{\n    int64_t from, to;\n    byn_slice_range(s.len, a, am, b, bm, incl, file, line, &from, &to);\n    return byn_str_slice(s, from, to, file, line);\n}\n");
            return $"{str}({Expr(s.Target)}, {tail})";
        }
        var st = _c.CType(s.Type);
        var tt = _c.CType(target);
        var name = "bynh_slice_" + _c.Key(target);
        var (param, len, ptr, arg) = target is ArrayType a
            ? ($"{tt}* x", a.Length.ToString(CultureInfo.InvariantCulture), "x->v", "&" + Expr(s.Target))
            : ($"{tt} x", "x.len", "x.ptr", Expr(s.Target));
        _c.Helper(name, $"static {st} {name}({param}, int64_t a, int am, int64_t b, int bm, bool incl, const char* file, int line)", () =>
            $"{{\n    int64_t from, to;\n    byn_slice_range({len}, a, am, b, bm, incl, file, line, &from, &to);\n    return ({st}){{{ptr} + from, to - from}};\n}}\n");
        return $"{name}({arg}, {tail})";
    }
