using System.Text;
using Bayan.Cli;
using Bayan.Syntax.Ast;
using Bayan.Syntax.Parsing;
using Bayan.Syntax.Text;

namespace Bayan.Tests;

/// <summary>
/// 017 T1: <c>bayan explain</c> of the self-hosted driver. <c>selfhost/driver/diagdocs.byn</c> holds one constant per
/// <c>docs/diagnostics/BYN####.md</c> (plan D2); <c>BAYAN_UPDATE=1</c> regenerates it. The rows compare stage 2 with <see cref="CliApp.Run"/>.
/// </summary>
[Collection(nameof(ToolchainEnvironment))]
[Trait("Law", "L028")]
public sealed class SelfhostDefaultT1Tests
{
    private static string DocsDir => Path.Combine(Golden.RepoRoot, "docs", "diagnostics");

    private static string DiagDocsPath => Path.Combine(SelfhostDriverHarness.DriverDir, "diagdocs.byn");

    private static string[] DocFiles() => Directory.GetFiles(DocsDir, "BYN*.md").Order(StringComparer.Ordinal).ToArray();

    private static string Escape(string text)
    {
        var sb = new StringBuilder();
        foreach (var r in text.EnumerateRunes())
        {
            switch (r.Value)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                case < 0x20: sb.Append("\\u{").Append(r.Value.ToString("x")).Append('}'); break;
                default: sb.Append(r.ToString()); break;
            }
        }
        return sb.ToString();
    }

    /// <summary>The text of <c>diagdocs.byn</c> for the files of <c>docs/diagnostics/</c>.</summary>
    internal static string Generate()
    {
        var sb = new StringBuilder();
        sb.Append("// GENERATED by SelfhostDefaultT1Tests (BAYAN_UPDATE=1): one constant per docs/diagnostics/BYN####.md (spec 017 plan D2). Do not edit.\n\n");
        var names = new List<string>();
        foreach (var file in DocFiles())
        {
            var name = Path.GetFileNameWithoutExtension(file);
            names.Add(name);
            sb.Append($"const doc{name[3..]}: string = \"{Escape(File.ReadAllText(file, new UTF8Encoding(false)))}\"\n");
        }
        sb.Append("\n/// The text of `docs/diagnostics/<name>.md` for an upper-case code, or null when there is none.\n");
        sb.Append("string? diagDoc(string name) {\n    switch name {\n");
        foreach (var name in names) sb.Append($"        case \"{name}\":\n            return doc{name[3..]}\n");
        sb.Append("        default:\n            return null\n    }\n}\n");
        return sb.ToString();
    }

    /// <summary>The constants of <c>diagdocs.byn</c>, read with the C# parser.</summary>
    private static Dictionary<string, string> Constants()
    {
        var tree = Parser.Parse(SourceText.FromFile(DiagDocsPath));
        Assert.False(tree.Diagnostics.Any(d => d.IsError), "diagdocs.byn has syntax errors");
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var member in tree.Root.Members)
            if (member is GlobalStatement { Statement: LocalDecl { Init: LiteralExpr { Kind: LiteralKind.String } lit } decl })
                result[decl.Name.Text] = lit.Text;
        return result;
    }

    [Fact]
    public void DiagDocsAreTheFilesByteForByte()
    {
        if (Environment.GetEnvironmentVariable("BAYAN_UPDATE") == "1") File.WriteAllText(DiagDocsPath, Generate(), new UTF8Encoding(false));
        Assert.True(File.Exists(DiagDocsPath), "diagdocs.byn is missing; run BAYAN_UPDATE=1 dotnet test --filter FullyQualifiedName~SelfhostDefaultT1Tests");
        var constants = Constants();
        var files = DocFiles();
        foreach (var file in files)
        {
            var name = "doc" + Path.GetFileNameWithoutExtension(file)[3..];
            Assert.True(constants.ContainsKey(name), $"{name} is missing from diagdocs.byn; run BAYAN_UPDATE=1");
            var expected = File.ReadAllBytes(file);
            var actual = Encoding.UTF8.GetBytes(constants[name]);
            Assert.True(expected.AsSpan().SequenceEqual(actual), $"{name} differs from {Path.GetFileName(file)} ({actual.Length} bytes, not {expected.Length}; first difference at {expected.AsSpan().CommonPrefixLength(actual)}, got `{constants[name][..Math.Min(60, constants[name].Length)]}`); run BAYAN_UPDATE=1");
        }
        Assert.Equal(files.Length, constants.Count);
        Assert.Equal(Generate(), File.ReadAllText(DiagDocsPath), ignoreLineEndingDifferences: false);
    }

    private static (int Exit, string Out, string Err) Oracle(string[] args)
    {
        var stdout = new StringWriter();
        var stderr = new StringWriter();
        var exit = CliApp.Run(args, stdout, stderr);
        return (exit, stdout.ToString().ReplaceLineEndings("\n"), stderr.ToString().ReplaceLineEndings("\n"));
    }

    private static void AssertSameAsCs(params string[] args)
    {
        var expected = Oracle(args);
        var actual = SelfhostDriverHarness.Run(args);
        var label = string.Join(' ', args);
        Assert.Equal(expected.Exit, actual.Exit);
        SelfhostEmitterHarness.AssertSame($"stdout of `{label}`", expected.Out, actual.Out);
        SelfhostEmitterHarness.AssertSame($"stderr of `{label}`", expected.Err, actual.Err);
    }

    public static IEnumerable<object[]> Rows() => new[]
    {
        new[] { "explain", "BYN0003" },
        new[] { "explain", "byn0003" },
        new[] { "explain", " byn0006 " },
        new[] { "explain", "BYN9999" },
        new[] { "explain", "BYN00" },
        new[] { "explain", "BYN00031" },
        new[] { "explain", "BYNabcd" },
        new[] { "explain", "BYN+003" },
        new[] { "explain", "../BYN0001" },
        new[] { "explain", "" },
        new[] { "explain", "0003" },
        new[] { "explain", "ABC0003" },
        new[] { "explain", " BYN0003" },
        new[] { "explain", "BYN0003 " },
        new[] { "explain", "\u0085byn0003" },
        new[] { "explain", "\u3000BYN0003 " },
        new[] { "explain", "\u200BBYN0003" },
        new[] { "explain", "BYN0003\u200B" },
        new[] { "explain", "\u00A0\u2003BYN0003\u2028\u1680" },
        new[] { "explain", " \t\n" },
        new[] { "lex" },
        new[] { "parse" },
        new[] { "types" },
        new[] { "check" },
        new[] { "explain" },
        new[] { "explain", "BYN0003", "BYN0006" },
        new[] { "--ascii", "explain", "BYN2780" },
    }.Select(a => new object[] { a });

    [Theory]
    [MemberData(nameof(Rows))]
    public void ExplainAsCliAppRun(string[] args) => AssertSameAsCs(args);

    [Fact]
    public void ExplainsEveryDocumentedCode()
    {
        foreach (var file in DocFiles())
            AssertSameAsCs("explain", Path.GetFileNameWithoutExtension(file));
    }
}
