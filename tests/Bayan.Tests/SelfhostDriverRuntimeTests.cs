using Bayan.Syntax.Ast;
using Bayan.Syntax.Parsing;
using Bayan.Syntax.Text;

namespace Bayan.Tests;

/// <summary>
/// 012 T4: <c>selfhost/driver/runtime.byn</c> carries <c>src/runtime/bayan-rt.h</c> and <c>bayan-rt.c</c> (embedded by
/// <c>Toolchain.cs:35-37</c>) as two raw-string constants. <c>BAYAN_UPDATE=1</c> regenerates the file; the check reads it
/// with the C# parser, so it needs no built binary.
/// </summary>
public sealed class SelfhostDriverRuntimeTests
{
    private static string RuntimeFile => Path.Combine(SelfhostDriverHarness.DriverDir, "runtime.byn");

    private static string RuntimeDir => Path.Combine(Golden.RepoRoot, "src", "runtime");

    private static string Generate()
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("// Generated by SelfhostDriverRuntimeTests under BAYAN_UPDATE=1 from src/runtime/; do not edit.\n");
        foreach (var (name, file) in new[] { ("runtimeHeader", "bayan-rt.h"), ("runtimeSource", "bayan-rt.c") })
        {
            var text = File.ReadAllText(Path.Combine(RuntimeDir, file)).Replace("\r\n", "\n");
            Assert.DoesNotContain("\"\"\"", text);
            Assert.False(text.StartsWith('\n') || text.EndsWith('"'), $"{file} cannot be a raw string");
            sb.Append($"\nconst {name}: string = \"\"\"{text}\"\"\"\n");
        }
        return sb.ToString();
    }

    /// <summary>The value of each top-level <c>const</c> string of <c>runtime.byn</c>, read with the C# parser.</summary>
    private static Dictionary<string, string> Constants()
    {
        var tree = SyntaxTree.Parse(SourceText.FromFile(RuntimeFile));
        Assert.Empty(tree.Diagnostics);
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var member in tree.Root.Members)
            if (member is GlobalStatement { Statement: LocalDecl { Kind: BindingKind.Const, Init: LiteralExpr lit } d })
                result[d.Name.Text] = lit.Text;
        return result;
    }

    [Fact]
    public void RuntimeConstantsEqualRuntimeFiles()
    {
        if (Golden.UpdateMode) File.WriteAllText(RuntimeFile, Generate());
        var constants = Constants();
        Assert.Equal(2, constants.Count);
        Assert.Equal(File.ReadAllText(Path.Combine(RuntimeDir, "bayan-rt.h")), constants["runtimeHeader"]);
        Assert.Equal(File.ReadAllText(Path.Combine(RuntimeDir, "bayan-rt.c")), constants["runtimeSource"]);
    }

    [Fact]
    public void StageOneBuildsWithRuntimeText()
    {
        Assert.True(File.Exists(SelfhostDriverHarness.Build()));
    }
}
