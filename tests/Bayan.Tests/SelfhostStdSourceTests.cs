using Bayan.Syntax.Ast;
using Bayan.Syntax.Parsing;
using Bayan.Syntax.Text;

namespace Bayan.Tests;

/// <summary>
/// 016 T2: <c>selfhost/semantics/stdsource.byn</c> carries <c>lib/std/**/*.byn</c> (embedded by
/// <c>Bayan.Semantics.csproj</c>) as one raw-string constant per file and <c>stdShippedSources</c>, the selfhost's
/// <c>StdLibrary.Shipped</c>. <c>BAYAN_UPDATE=1</c> regenerates the file; the check needs no built binary.
/// </summary>
public sealed class SelfhostStdSourceTests
{
    private static string StdSourceFile => Path.Combine(SelfhostSemanticsHarness.SemanticsDir, "stdsource.byn");

    private static string StdDir => Path.Combine(Golden.RepoRoot, "lib", "std");

    /// <summary>Each <c>*.byn</c> under <paramref name="dir"/>: its path under it with <c>/</c>, in ordinal order, and its text.</summary>
    private static List<(string Path, string Text)> Files(string dir) =>
        Directory.EnumerateFiles(dir, "*.byn", SearchOption.AllDirectories)
            .Select(f => (Path: Path.GetRelativePath(dir, f).Replace('\\', '/'), Text: File.ReadAllText(f).Replace("\r\n", "\n")))
            .OrderBy(f => f.Path, StringComparer.Ordinal)
            .ToList();

    private static string Generate(string dir)
    {
        var files = Files(dir);
        var sb = new System.Text.StringBuilder();
        sb.Append("// Generated by SelfhostStdSourceTests under BAYAN_UPDATE=1 from lib/std/; do not edit.\n\n");
        sb.Append("/// The C# `StdLibrary.Shipped` files (StdLibrary.cs:36): every `lib/std/**/*.byn`, its path under `std/`.\n");
        sb.Append("List<StdSource> stdShippedSources() {\n");
        if (files.Count == 0)
            sb.Append("    return List<StdSource>()\n");
        else
        {
            sb.Append("    var sources = List<StdSource>()\n");
            for (var i = 0; i < files.Count; i++)
                sb.Append($"    sources.append(StdSource {{ path: \"{files[i].Path}\", text: stdSource{i} }})\n");
            sb.Append("    return sources\n");
        }
        sb.Append("}\n");
        for (var i = 0; i < files.Count; i++)
        {
            var (path, text) = files[i];
            Assert.DoesNotContain("\"\"\"", text);
            Assert.False(text.StartsWith('\n') || text.EndsWith('"'), $"{path} cannot be a raw string");
            Assert.DoesNotContain('"', path);
            sb.Append($"\nconst stdSource{i}: string = \"\"\"{text}\"\"\"\n");
        }
        return sb.ToString();
    }

    /// <summary>The (path, text) pairs <paramref name="source"/> lists, read with the C# parser.</summary>
    private static List<(string Path, string Text)> Listed(string source)
    {
        var tree = SyntaxTree.Parse(SourceText.FromString("stdsource.byn", source));
        Assert.Empty(tree.Diagnostics);
        var constants = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var member in tree.Root.Members)
            if (member is GlobalStatement { Statement: LocalDecl { Kind: BindingKind.Const, Init: LiteralExpr lit } d })
                constants[d.Name.Text] = lit.Text;
        var listed = new List<(string, string)>();
        foreach (var line in source.Split('\n'))
        {
            var m = System.Text.RegularExpressions.Regex.Match(line, "^    sources\\.append\\(StdSource \\{ path: \"([^\"]*)\", text: (stdSource[0-9]+) \\}\\)$");
            if (m.Success) listed.Add((m.Groups[1].Value, constants[m.Groups[2].Value]));
        }
        Assert.Equal(constants.Count, listed.Count);
        return listed;
    }

    [Fact]
    public void StdSourceEqualsLibStd()
    {
        if (Golden.UpdateMode) File.WriteAllText(StdSourceFile, Generate(StdDir));
        Assert.Equal(Generate(StdDir), File.ReadAllText(StdSourceFile));
        Assert.Equal(Files(StdDir), Listed(File.ReadAllText(StdSourceFile)));
    }

    /// <summary>The generator on a fixture tree: a nested module, a test file and text with braces, which <c>lib/std/</c> need not hold.</summary>
    [Fact]
    public void GeneratedFileListsEveryFile()
    {
        var dir = Path.Combine(Golden.RepoRoot, "tmp", "std-source-fixture");
        if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
        foreach (var (path, text) in new[] { ("probe/probe.byn", "public i64 one() {\n    return 1\n}\n"), ("probe/probe.test.byn", "test \"t\" {}\n"), ("a/b/b.byn", "// {x}\n") })
        {
            var full = Path.Combine(dir, path);
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            File.WriteAllText(full, text);
        }
        var listed = Listed(Generate(dir));
        Assert.Equal(["a/b/b.byn", "probe/probe.byn", "probe/probe.test.byn"], listed.Select(f => f.Path));
        Assert.Equal(Files(dir), listed);
    }
}
