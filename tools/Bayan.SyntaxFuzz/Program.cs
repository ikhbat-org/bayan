using System.Diagnostics;
using System.Text;
using Bayan.Syntax.Lexing;
using Bayan.Syntax.Parsing;
using Bayan.Syntax.Text;

// Feeds the C# lexer and parser generated inputs and checks lexer invariants and that the parser never throws.
// Inputs: every golden case as is, then splices of golden cases, grammar fragments and random bytes.

int seed = 1, count = 20000;
var cases = Path.Combine("tests", "cases");
for (var i = 0; i + 1 < args.Length; i += 2)
{
    switch (args[i])
    {
        case "--seed": seed = int.Parse(args[i + 1]); break;
        case "--count": count = int.Parse(args[i + 1]); break;
        case "--cases": cases = args[i + 1]; break;
        default: return Usage();
    }
}
if (args.Length % 2 != 0 || !Directory.Exists(cases)) return Usage();

var corpus = Directory.GetFiles(cases, "*.byn", SearchOption.AllDirectories).Order(StringComparer.Ordinal).Select(File.ReadAllBytes).ToArray();
if (corpus.Length == 0)
{
    Console.Error.WriteLine($"no *.byn files under {cases}");
    return 2;
}
string[] fragments =
[
    "\"", "$\"", "{", "}", "\\", "\\u{", "\\{", "'", "/*", "*/", "//", "///", "\n", "\r\n", " ", "\t", "0x", "0b", "0o", "1_000", "1e", "1.5",
    ".", "..", "..<", "_", "é", "‮", "⁦", "ﷺ", "𝔸", "﻿", "#!", "#:", "`", "@", "r\"", "\"\"\"", "é", "٣", "\0", "+%", "-|",
    "=>", "?.", "(", ")", "if", "unless", "while", "int", "fails",
];
var random = new Random(seed);
var failures = 0;
var seen = new HashSet<string>();
var strict = new UTF8Encoding(false, true);

for (var n = 0; n < count; n++)
{
    var input = n < corpus.Length ? corpus[n] : Generate();
    var source = new SourceText("fuzz.byn", input);
    LexResult lexed;
    var clock = Stopwatch.StartNew();
    try { lexed = Lexer.Lex(source); }
    catch (Exception e) { Fail("lexer threw " + e.GetType().Name, input, e.ToString()); continue; }
    if (clock.ElapsedMilliseconds > 500) Fail("lexer slow", input, $"{clock.ElapsedMilliseconds} ms");
    CheckTokens(input, lexed);
    CheckDiagnostics(input, lexed);
    if (Signature(Lexer.Lex(new SourceText("fuzz.byn", input))) != Signature(lexed)) Fail("lexer not deterministic", input, "");
    CheckFixes(input, lexed);

    clock.Restart();
    try { SyntaxTree.Parse(source); }
    catch (Exception e) { Fail("parser threw " + e.GetType().Name, input, e.ToString()); }
    if (clock.ElapsedMilliseconds > 1000) Fail("parser slow", input, $"{clock.ElapsedMilliseconds} ms");
}
Console.WriteLine($"{count} inputs ({corpus.Length} golden cases, seed {seed}): {failures} distinct failures");
return failures == 0 ? 0 : 1;

static int Usage()
{
    Console.Error.WriteLine("usage: Bayan.SyntaxFuzz [--seed N] [--count N] [--cases DIR]   (run from the repository root)");
    return 2;
}

byte[] Generate()
{
    var bytes = new MemoryStream();
    for (int part = 0, parts = random.Next(1, 12); part < parts; part++)
    {
        switch (random.Next(5))
        {
            case 0:
            {
                var c = corpus[random.Next(corpus.Length)];
                if (c.Length == 0) break;
                var at = random.Next(c.Length);
                bytes.Write(c, at, random.Next(Math.Min(200, c.Length - at) + 1));
                break;
            }
            case 1 or 2:
                bytes.Write(Encoding.UTF8.GetBytes(fragments[random.Next(fragments.Length)]));
                break;
            case 3:
                for (int i = 0, k = random.Next(1, 6); i < k; i++) bytes.WriteByte((byte)random.Next(0x20, 0x7F));
                break;
            default:
                for (int i = 0, k = random.Next(1, 4); i < k; i++) bytes.WriteByte((byte)random.Next(256));
                break;
        }
    }
    if (random.Next(4) != 0) return bytes.ToArray();
    // Splice the generated bytes into a whole golden case.
    var host = corpus[random.Next(corpus.Length)];
    var split = random.Next(host.Length + 1);
    return [.. host.AsSpan(0, split), .. bytes.ToArray(), .. host.AsSpan(split)];
}

void CheckTokens(byte[] input, LexResult lexed)
{
    var tokens = lexed.Tokens;
    if (tokens.Length == 0 || tokens[^1].Kind != TokenKind.EndOfFile || tokens[^1].Start != input.Length)
        Fail("no end-of-file token at the end", input, tokens.Length == 0 ? "no tokens" : tokens[^1].ToString());
    var eofs = 0;
    foreach (var t in tokens) if (t.Kind == TokenKind.EndOfFile) eofs++;
    if (eofs != 1) Fail("end-of-file token count", input, eofs.ToString());
    var valid = IsValidUtf8(input);
    var previous = 0;
    foreach (var t in tokens)
    {
        if (t.Start < previous || t.Length < 0 || t.End > input.Length)
        {
            Fail("token out of order or bounds", input, $"{t} after {previous}");
            return;
        }
        if (valid && (!OnBoundary(input, t.Start) || !OnBoundary(input, t.End)))
        {
            Fail("token splits a code point", input, t.ToString());
            return;
        }
        var gap = input.AsSpan(previous, t.Start - previous);
        if (t.HasNewlineBefore && !gap.Contains((byte)'\n')) Fail("NewlineBefore without a newline", input, t.ToString());
        if (t.HasTriviaBefore && gap.Length == 0) Fail("TriviaBefore without a gap", input, t.ToString());
        if (t.HasDoc && (t.DocStart < 0 || t.DocStart + t.DocLength > t.Start)) Fail("doc comment span", input, $"{t} doc {t.Doc}");
        previous = t.End;
    }
}

void CheckDiagnostics(byte[] input, LexResult lexed)
{
    foreach (var d in lexed.Diagnostics)
    {
        if (d.Span.Start < 0 || d.Span.Start + d.Span.Length > input.Length) Fail("diagnostic span " + d.Code, input, d.Span.ToString());
        if (d.Fix is { } f && (f.Span.Start < 0 || f.Span.Start + f.Span.Length > input.Length)) Fail("fix span " + d.Code, input, f.Span.ToString());
    }
}

// Applying a fix must not throw, and must leave fewer diagnostics with its code.
void CheckFixes(byte[] input, LexResult lexed)
{
    foreach (var d in lexed.Diagnostics.Where(d => d.Fix is not null).Take(3))
    {
        var f = d.Fix!;
        if (f.Span.Start < 0 || f.Span.Start + f.Span.Length > input.Length) continue;
        byte[] applied = [.. input.AsSpan(0, f.Span.Start), .. Encoding.UTF8.GetBytes(f.Replacement), .. input.AsSpan(f.Span.Start + f.Span.Length)];
        try
        {
            var after = Lexer.Lex(new SourceText("fuzz.byn", applied));
            if (after.Diagnostics.Count(x => x.Code == d.Code) >= lexed.Diagnostics.Count(x => x.Code == d.Code))
                Fail("fix does not fix " + d.Code, input, $"{f.Span} -> \"{f.Replacement}\"", key: d.Message);
        }
        catch (Exception e)
        {
            Fail("lexer threw after a fix for " + d.Code, applied, e.ToString());
        }
    }
}

// Reports a failure once per kind and key (the detail's first line by default), with the input as base64 so it can be replayed.
void Fail(string kind, byte[] input, string detail, string? key = null)
{
    if (!seen.Add(kind + "\n" + (key ?? detail.Split('\n')[0]))) return;
    failures++;
    var text = new string(Encoding.UTF8.GetString(input).Replace("\n", "\\n").Take(200).ToArray());
    Console.WriteLine($"FAIL {kind}: {detail}\n  input ({input.Length} bytes, base64): {Convert.ToBase64String(input)}\n  text: {text}");
}

static string Signature(LexResult lexed)
{
    var sb = new StringBuilder();
    foreach (var t in lexed.Tokens) sb.Append($"{t.Kind}@{t.Start}+{t.Length}/{(int)t.Flags}/{t.DocStart}+{t.DocLength},");
    sb.Append('|');
    foreach (var d in lexed.Diagnostics) sb.Append($"{d.Code}@{d.Span},");
    return sb.ToString();
}

bool IsValidUtf8(byte[] bytes)
{
    try
    {
        strict.GetString(bytes);
        return true;
    }
    catch (DecoderFallbackException)
    {
        return false;
    }
}

static bool OnBoundary(byte[] bytes, int i) => i <= 0 || i >= bytes.Length || (bytes[i] & 0xC0) != 0x80;
